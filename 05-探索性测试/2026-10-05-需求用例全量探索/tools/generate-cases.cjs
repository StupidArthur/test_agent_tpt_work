function add(module, key, anchor, setup, rows, defaults = {}) {
  const src = sources[key];
  const exact = src.lines.findIndex(l => l.trim() === anchor);
  const line = (exact >= 0 ? exact : src.lines.findIndex(l => l.includes(anchor))) + 1;
  if (!line) throw new Error('原文定位失败: ' + key + ': ' + anchor);
  modules[module] ??= {name: module, count: 0};
  for (const row of rows.trim().split('\n').filter(Boolean)) {
    const cells = row.split('|');
    if (cells.length < 3 || cells.length > 5) throw new Error('字段错误:' + row);
    const [title, action, expected, flag = '', basis = defaults.basis || '文档要求'] = cells;
    const n = ++modules[module].count;
    cases.push({id: `${module}-${String(n).padStart(3, '0')}`, module, title,
      priority: n <= 3 ? 'P0' : (defaults.priority || 'P1'), depth: defaults.depth || (basis === '开放探索' ? '入口与实际行为盘点' : '业务闭环/对应检查点'),
      requirement_status: src.status, basis, source: {key, file: src.file, line, section: anchor, quote: src.lines[line-1].trim()},
      preconditions: ['按README完成环境检查；使用本轮测试数据和当前可用的低级模型。', setup],
      steps: ['确认当前入口、账号、空间、项目与测试对象，保存初始状态。', ...action.split('；'), '等待可观察终态；回读对应页面/数据/产物，保存实际结果并记录差异。'],
      expected: expected.split('；'), constraints: flag && flag !== '规则推导' ? flag.split(',') : [],
      evidence_required: ['初始状态与操作序列', '终态截图或DOM/接口记录', '与本轮case标记对应的结果；持久操作须独立回读', '差异或阻塞说明及相关证据路径'],
      cleanup: '按变更清单恢复本轮临时配置；只处理明确归属本轮的夹具。不得删除记忆或已有用户数据；受限清理记入交接。',
      initial_status: '未执行'});
  }
}

