//#region src/elevated.ts
/**
* 沙箱提权 spawn：以沙箱用户身份拉起 `sandbox-runner.exe`，拿到真写隔离。
*
* 与非提权路径的本质差别 = **base token 是谁**：非提权 base = 当前用户 ⇒ 仅 LUA 限权、无写隔离；
* 提权 base = 沙箱用户（另一低权账户）⇒ 对真实用户文件默认无写权限，只有被 ACL 授权的工作区可写。
*
* 前提（一次性，见 `setup.ts`）：`sandbox-setup.exe` 已产出
* `<codex_home>/.sandbox/sandbox_users.json`（DPAPI 凭据）与 `setup_marker.json`，并把沙箱组锁进
* `<codex_home>/.sandbox/`。父进程**不需要**提权。
*
* 三个实测坑：① runner exe 不能放在真实用户 TEMP/家目录下（沙箱用户读不到即挂）⇒
* 物化到 `<codex_home>/.sandbox/bin/`；② 管道 DACL 必须同时授沙箱用户与当前用户（否则父进程连不上）；
* ③ 提权 spawn 用 `CREATE_NO_WINDOW` 压窗口。
* @module
*/
/** 沙箱用户可读的 runner 落点（codex `sandbox_bin_dir` = `<codex_home>/.sandbox-bin`；setup 对它给沙箱组 RX）。 */
function sandboxRunnerDir(sandboxHome) {
	return join(sandboxHome, ".sandbox-bin");
}
/**
* 把 runner exe 物化到沙箱用户可读的目录（幂等：同名同大小则跳过）。
* @returns 沙箱用户可达的 runner 路径。
*/
function materializeRunnerForSandbox(sandboxHome, sourceExe) {
	const dir = sandboxRunnerDir(sandboxHome);
	mkdirSync(dir, { recursive: true });
	const dest = join(dir, "sandbox-runner.exe");
	if (!existsSync(dest) || statSync(dest).size !== statSync(sourceExe).size) copyFileSync(sourceExe, dest);
	return dest;
}
/**
* 给命名管道构造 SECURITY_ATTRIBUTES：授 SYSTEM + 内置管理员 + 沙箱用户 + 当前用户（缺当前用户则
* 非提权父进程连不上；缺沙箱用户则提权 runner 连不上）。
*
* ⚠ 当前用户 SID 取自**进程 token**（`currentUserSid`），不按 USERNAME 查名——加域机上同名本地账号
* 会被优先解析到，导致 ACE 匹配不上真实 token（实测踩坑：管道 CreateFileW 报 ACCESS_DENIED 5）。
*/
function pipeSecurityAttributes(sandboxUsername) {
	const sddl = `D:(A;;GA;;;SY)(A;;GA;;;BA)(A;;GA;;;${lookupAccountSid(sandboxUsername)})(A;;GA;;;${currentUserSid()})`;
	return securityAttributesFromSddl(sddl);
}
/** Windows 命令行参数加引号（含空格/特殊字符时用双引号包裹）。 */
function quoteArg(arg) {
	return /[\s"]/u.test(arg) ? `"${arg.replace(/(["\\])/gu, "\\$1")}"` : arg;
}
/**
* 以沙箱用户拉起 runner（`CreateProcessWithLogonW`）。
* @param exePath - 沙箱用户可读的 runner exe（`materializeRunnerForSandbox` 的返回）。
* @param args - runner argv（`--pipe-in=… --pipe-out=…`）。
* @param credential - 沙箱用户凭据（`readSandboxUsers` 解出）。
* @param cwd - 子进程工作目录（取 codex_home，沙箱用户可读）。
*/
function spawnRunnerAsSandboxUser(exePath, args, credential, cwd) {
	const commandLine = [exePath, ...args].map(quoteArg).join(" ");
	return spawnAsSandboxUser(credential, commandLine, cwd);
}
/** 便捷入口：读离线沙箱用户凭据。 */
function offlineSandboxCredential(sandboxHome) {
	return readSandboxUsers(sandboxHome).offline;
}
