//#region src/upstream-acl.ts
/**
* 上游 dsh ACL 沙箱库（`@deepseek-ai/dsh-sandbox-windows-acl`）的**唯一**取用点。
*
* 为什么不是 `import` 语句而是惰性 `require(esm)`（三条各自成立的理由）：
*
*  1. **本包的 `index` 被 `dsh-sandbox-local` 静态 import**，而 sandbox-local 是各平台常驻 entry
*     （见 `win32-load.ts` 的同款告诫）。上游那一串模块在 import 期就拉起 `koffi` 与
*     `@deepseek-ai/dsh-win32-process` ⇒ 顶层静态 import 等于让 Linux/macOS 宿主为一个 Windows-only
*     后端加载原生绑定。
*  2. seam 侧的调用点全是**同步**的（`AclWriteGrant.create()` / `workspaceWriteSid()` 都在
*     `windowsAclRunnerArgv()` 的同步路径上）⇒ 动态 `import()` 的 Promise 在这里用不了。
*     Node ≥22.12 的 `require(esm)` 对无顶层 await 的 ESM 图可同步取命名空间（本机实测 11 ms，
*     导出内容 `AclSandbox/AclWriteGrant/assertTempRootOutsideWorkspace/tempWriteSid/workspaceWriteSid`，
*     且 `workspaceWriteSid('C:\\Projects\\tpt-work')` 与我方原副本逐字节同形）。
*  3. ACL 档以外（Linux/macOS、以及提权档的宿主装配）根本不该为它付加载成本。
*
* ⚠ 上游是**默认档的实现本体**：ACL 档下 SID 派生、授权语义、runner 全部由它负责，我方不再留
* 一份同形副本（副本会漂）。要换实现版本 = 改 pin，不是改这里。
* @module @tpt-work/sandbox/upstream-acl
*/
/** 上游包名（ACL 档的实现本体）。只用于错误文案；**加载点用的是字面量**，见下。 */
const UPSTREAM_ACL_PACKAGE = "@deepseek-ai/dsh-sandbox-windows-acl";
const requireModule = createRequire(import.meta.url);
let cached;
/**
* 取上游模块（首次调用时加载并缓存）。
*
* ⚠ 这里**必须**用字符串字面量调 `require`，不能改成用上面那个常量：打包链
* `bakeShippedExternal` 靠扫产物里的裸串决定「哪些包要有真文件随包」，变量拼出来的 specifier
* 扫不到 ⇒ 包不会随包 ⇒ 装机上 ACL 档（也就是默认档）第一次受限执行就 `Cannot find package`。
* 同一个包还另有一条兜底：它已登记进 `packages/host/external.json`（implementation/sandbox-decodex-rename-acl-elevated-modes W1 起该清单是一等
* 随包来源）。两条都要在，别再退回「只靠一条」。
* @returns 上游命名空间中本包用到的那一小片。
* @throws 上游包不在树上时抛出带指明的错误（fail-closed：绝不静默退回到另一档的实现）。
*/
function upstreamAcl() {
	if (cached !== void 0) return cached;
	try {
		cached = requireModule("@deepseek-ai/dsh-sandbox-windows-acl");
	} catch (error) {
		throw new Error(`受限执行需要 ${UPSTREAM_ACL_PACKAGE}（ACL 档的实现本体），但它无法解析：${error instanceof Error ? error.message : String(error)}`, { cause: error });
	}
	return cached;
}
//#endregion
//#region src/workspace-sid.ts
/**
* 能力 SID 派生：**一律转发上游** `@deepseek-ai/dsh-sandbox-windows-acl`（implementation/sandbox-decodex-rename-acl-elevated-modes W4）。
*
* 这里原本是自己实现的一份 `S-1-4-x-y` / `S-1-4-x-y-1` 派生（sha256 + 30-bit 子权威），
* 与上游逐字节同形——但「同形」是靠人核对维持的，漂了不会红。ACL 档既然把整条链交回上游，
* SID 就只能是**同一个函数**而不是两份同形实现：
*
*  - seam 用这里的 `workspaceWriteSid()` 算 `--write-sid`，runner 用上游同名函数校验并落 ACE
*    ⇒ 一旦两份实现有微差（路径规范化、盐串、取模边界），workspace-write 就静默写不进工作区；
*  - 提权档也要同一个 SID（setup 把写 ACE 授给它），否则两档之间换档等于换身份。
*
* 转发是惰性的（见 `upstream-acl.ts`）：非 Windows 宿主在 import 期不因此拉起 koffi。
* @module @tpt-work/sandbox/workspace-sid
*/
/**
* 工作区写能力 SID（`S-1-4-x-y`）。
* @param workspaceRoot - 规范工作区绝对路径。
* @returns SDDL 字符串（由上游派生，跨会话/重启稳定，故工作区 ACE 可复用）。
*/
function workspaceWriteSid(workspaceRoot) {
	return upstreamAcl().workspaceWriteSid(workspaceRoot);
}
/**
* 单个私有 temp 目录的写能力 SID（`S-1-4-x-y-1`）：与所有双子权威的工作区 SID 域区分，
* 使同一工作区的兄弟会话无法用常驻工作区能力进彼此的 temp。
* @param tempDir - 私有 temp 目录绝对路径。
* @returns SDDL 字符串。
*/
function tempWriteSid(tempDir) {
	return upstreamAcl().tempWriteSid(tempDir);
}
/**
* 只读模式的确定性 cap SID：不授任何写 ACE，只满足 SpawnRequest 的 cap_sid 非空要求。
* 用上游派生同一个命名空间，保证「同一个串」在两档里含义一致。
* @returns SDDL 字符串。
*/
function readOnlyCapSid() {
	return upstreamAcl().workspaceWriteSid("read-only");
}
