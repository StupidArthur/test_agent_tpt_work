/**
* 工作区 / 私有临时目录的规范目录边界检查。
*
* 分工（implementation/sandbox-decodex-rename-acl-elevated-modes W4）：
*  - `assertTempRootOutsideWorkspace` = **转发上游**（seam 在 ACL 档与提权档都会调它，两档必须
*    给出同一个答案；自己再留一份镜像实现就是下一个漂移源）。
*  - `assertPrivateTempDisjoint` = 本包**独有**的加严：上游导出内容里没有这一条（它的
*    `AclSandboxOptions` 只校 temp 与 workspace 的关系），而提权档把工作区与 temp 两种能力挂在
*    同一份 DACL 体系上，任一继承方向的重叠都会把两种能力合并 ⇒ 我方自己判。
* @module @tpt-work/sandbox/path-boundary
*/
/** `root` 与 `candidate` 是否为同一规范目录，或 `root` 包含 `candidate`。 */
function containsDirectory(root, candidate) {
	const relation = relative(realpathSync.native(root), realpathSync.native(candidate));
	return relation === "" || !isAbsolute(relation) && relation !== ".." && !relation.startsWith(`..${sep}`);
}
/**
* 拒绝位于工作区内的 temp 父根：其下每个子目录都会继承常驻工作区能力。
* @param workspaceRoot - 接收常驻 ACE 的规范工作区根。
* @param tempRoot - 私有 temp 子目录将创建于其下的既有父目录。
*/
function assertTempRootOutsideWorkspace(workspaceRoot, tempRoot) {
	upstreamAcl().assertTempRootOutsideWorkspace(workspaceRoot, tempRoot);
}
/**
* 拒绝实际私有 temp 目录与任一可写目录重叠：任一继承方向都会合并两种能力。
* @param writableDirs - 承载常驻工作区能力的目录。
* @param tempDir - 承载可回收 temp 能力的既有目录。
*/
function assertPrivateTempDisjoint(writableDirs, tempDir) {
	for (const writableDir of writableDirs) if (containsDirectory(writableDir, tempDir) || containsDirectory(tempDir, writableDir)) throw new Error(`[tpt-sandbox] private temp directory must be disjoint from writable directories: writable=${writableDir}; temp=${tempDir}`);
}
