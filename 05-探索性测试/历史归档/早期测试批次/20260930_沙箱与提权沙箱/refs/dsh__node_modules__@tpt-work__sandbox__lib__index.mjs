/**
* 受限执行的**档位**（implementation/sandbox-decodex-rename-acl-elevated-modes W4）：`acl` = 直接复用 dsh 官方 `windows-acl` 库（WRITE_RESTRICTED
* token + 能力 SID，默认档）；`elevated` = 我方提权路径（codex runner 帧 IPC + 沙箱用户，
* 需一次 UAC setup）。
*
* 为什么需要一个独立模块 + 状态文件：档位是**用户设置**（`tpt-sandbox.mode`，由
* `@tpt-work/sandbox-ui` 的宿主半持有），但消费点在两个够不着 `ctx` 的地方——
*  1. `dsh-sandbox-local` 的 `windowsAclRunnerInvocation()`（它只问本包要 runner argv，见
*     `patches/@deepseek-ai__dsh-sandbox-local.patch`）；
*  2. 被 spawn 出去的 runner 子进程（它连本包的模块状态都没有）。
* ⇒ 单一写入方（宿主半在设置变更时调 `setSandboxMode`），三条读取路径：进程内状态 →
* `process.env.TPT_SANDBOX_MODE`（子进程继承）→ 状态文件（无 ctx 的 CLI/探针）→ 默认 `acl`。
*
* ⚠ 默认必须是 `acl`：`elevated` 依赖一次提权 setup 的产物，未装过的机器上它 fail-closed；
* 默认档不能在用户没授权时把受限执行整条关掉。
* @module @tpt-work/sandbox/mode
*/
/** 默认档：非提权 ACL（需求方 2026-09-15 口径「默认为 ACL 模式」）。 */
const DEFAULT_SANDBOX_MODE = "acl";
/**
* 档位状态文件。
*
* 落点是 `defaultSandboxHome()` 而不是 `runnerInstallDir()`，为的是**可测**：前者可被
* `TPT_SANDBOX_HOME` 整体重定向，后者写死在 `homedir()` 下——挂在后者上，任何碰到
* `setSandboxMode` 的单测都会往真实用户数据根写文件（R8 明令的那一类）。档位文件本来就是
* 沙箱自己的状态，跟 setup 产物同处一个可重定向的根，语义也更顺。
*/
function sandboxModeFile() {
	return join(defaultSandboxHome(), "mode.json");
}
/** 宿主半写入的唯一入口：进程内状态 + env（子进程继承）+ 状态文件（无 ctx 的进程）。 */
let currentMode;
/** 是否成功持久化过（失败只降级，不影响进程内档位）。 */
let persistWarned = false;
function isMode(value) {
	return value === "acl" || value === "elevated";
}
/**
* 设定档位。三个落点缺一不可：
*  - 进程内状态：同进程内的 `sandboxMode()` 读它（最快、无 IO）；
*  - `process.env.TPT_SANDBOX_MODE`：被 seam spawn 的 runner 子进程靠继承拿到；
*  - 状态文件：`setup-cli` 一类没有 dsh 上下文的进程，以及进程重启前的最后读数。
* 写文件失败（只读盘、权限）只 warn 一次，不抛——档位本身已在进程内与 env 生效。
* @param mode - 目标档位。
*/
function setSandboxMode(mode) {
	currentMode = mode;
	process.env.TPT_SANDBOX_MODE = mode;
	try {
		const file = sandboxModeFile();
		mkdirSync(defaultSandboxHome(), { recursive: true });
		writeFileSync(file, `${JSON.stringify({ mode }, void 0, 2)}\n`);
	} catch (error) {
		if (!persistWarned) {
			persistWarned = true;
			process.stderr.write(`[tpt-sandbox] 档位状态文件写入失败（档位仍在本进程与其子进程生效）：${error instanceof Error ? error.message : String(error)}\n`);
		}
	}
}
/**
* 当前生效档位。优先级：进程内状态 > `TPT_SANDBOX_MODE` env > 状态文件 > 默认 `acl`。
* env 与文件里的非法值一律忽略（fail-safe 到默认档，绝不因为一个写坏的字符串退回提权档）。
* @returns 生效档位。
*/
function sandboxMode() {
	if (currentMode !== void 0) return currentMode;
	const fromEnv = process.env.TPT_SANDBOX_MODE;
	if (isMode(fromEnv)) return fromEnv;
	const fromFile = readModeFile();
	if (fromFile !== void 0) return fromFile;
	return "acl";
}
/** 读状态文件里的档位（不存在/坏 JSON/字段不认识 ⇒ undefined）。 */
function readModeFile() {
	const file = sandboxModeFile();
	if (!existsSync(file)) return void 0;
	try {
		const mode = JSON.parse(readFileSync(file, "utf8")).mode;
		return isMode(mode) ? mode : void 0;
	} catch {
		return;
	}
}
