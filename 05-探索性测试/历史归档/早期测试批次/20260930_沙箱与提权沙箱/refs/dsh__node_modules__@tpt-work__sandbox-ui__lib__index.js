import { Remote, TypertRemoteService } from "@deepseek-ai/dsh-typert-protocol";
import z from "@deepseek-ai/schemastery";
import { currentUserAccountName, defaultSandboxHome, ensureSandboxSetup, resolveRunnerExe, resolveSetupExe, sandboxMode, sandboxSetupComplete, setSandboxMode } from "@tpt-work/sandbox";
import { rmSync } from "node:fs";
import { join } from "node:path";
import { answerDangerConfirmation, requireDangerConfirmation } from "@tpt-work/danger-verbs";
//#region src/index.ts
/**
* `@tpt-work/sandbox-ui` 的 **node 半**（dual-face client 包的宿主侧）。
*
* 职责 = 把受限执行的「档位 / 状态 / 安装 / 卸载」暴露成 dsh Remote（`ctx.remote.tptSandbox.*`），
* 并注册本插件的**用户设置命名空间** `tpt-sandbox`（浏览器半那张卡片就挂在它下面）。真正的受限
* 执行逻辑仍在 `@tpt-work/sandbox`（本包只做界面 + 提权触发的转发 + **档位的唯一写入方**）。
*
* ⚠ **设置命名空间不是装饰，但它的职责在 0.1.6-alpha.2 缩了一块**：这里注册它是**写值的落点**
* （`ctx.settingsScope` 按命名空间取作用域，档位读写、`settings/updated` 订阅都挂在这），浏览器半
* 那张配置卡也仍按它取词表。⚠ 但它**不再**充当卡片的槽键：旧格 `settings.plugin.item`（按「宿主服务了
* 哪些设置命名空间」派发 keyed 卡片）已被上游删除，浏览器半改挂 `plugins.item`（列表层直显，条目
* id = `sandbox-ui`，与官方面卡同层）。只留命名空间而漏掉那格注册 ⇒ 插件页里什么都看不到。
*
* ⚠ **档位是设置，但消费点在够不着 `ctx` 的地方**（被 seam spawn 的 runner 子进程、以及没有 dsh
* 上下文的 CLI/探针），所以这里持有 `mode` 并把每次变更**推**进 `@tpt-work/sandbox` 的
* `setSandboxMode()`（进程内 + env + 状态文件三处落点，见该模块）。三个推的时机缺一不可：
*  1. 注册时（装配完成 ⇒ 开机就按用户上次的选择生效，早于任何受限命令）；
*  2. `settings/updated` 事件（用户从通用设置编辑器或别处改的，不走本包 Remote）；
*  3. 每次 `status()`（卡片每次挂载/操作后都读，兜住前两者没赶上的窗口）。
* @module @tpt-work/sandbox-ui
*/
/** 本插件的设置命名空间（必须是小写连字符标识；0.1.6-alpha.2 起只是**写值的作用域键**，不再是卡片在槽里的 key）。 */
const SETTINGS_NAMESPACE = "tpt-sandbox";
/** 本插件用户设置的形状（schemastery 校验）。导出仅供 `tests/quality` 的 volatile 投影判据读取。 */
const SandboxSettingsSchema = z.object({ 
/**
* 受限执行档位。默认 `acl`：不提权、装完即用（需求方 2026-09-15 口径）。
* ⚠ 枚举写法是 schemastery 的 `z.union([...])`（字面量数组即枚举），**不是** zod 的 `z.enum`
* ——本包 `z` 来自 `@deepseek-ai/schemastery`，它没有 `enum`（同口径见 `@tpt-work/llm-tpt`
* 的 `transport`/`cacheRetention`）；浏览器半的 wire schema 才是 zod。
* ⚠ `.volatile()` 不可省：rc.2 表单投影只收 volatile 字段，缺了它整段从 `describe()` 消失、
* 设置卡片恒 `unavailable`（2026-09-28 真机缺陷族，同 `@tpt-work/dev-mode`）。
*/
mode: z.union(["acl", "elevated"]).default("acl").volatile() });
/** 档位 → 实际隔离强度。分开算是有代价的：选了提权又没装，用户必须看到「拒绝执行」而不是「有沙箱」。 */
function isolationOf(mode, supported, setupComplete) {
	if (!supported) return "unsupported";
	if (mode === "acl") return "write-restricted";
	return setupComplete ? "elevated" : "not-installed";
}
/** 各档位×各状态的人话。文案与真实边界对齐：ACL 档**只限写**，不写成提权档那种强隔离。 */
function detailOf(mode, isolation, runnerReady) {
	if (isolation === "unsupported") return "当前平台不支持受限执行，仅 Windows 可用。";
	if (mode === "acl") return "ACL 档：命令只能在被授权目录内写入，工作区之外的写入会被拒绝。写限制由 Windows 受限令牌实现，不需要管理员权限；但只限制写入——读文件、访问网络、枚举进程都不受限制。";
	if (isolation === "elevated") return "提权档：命令以独立低权用户运行，工作区之外的写入会被拒绝，隔离比 ACL 档更强。";
	return runnerReady ? "提权档尚未安装：需要一次管理员授权完成沙箱安装。安装完成前受限命令会直接拒绝执行（不会静默放行）。" : "提权档组件未就绪：sandbox-runner.exe 尚未下载，请检查网络后重试，或先切回 ACL 档。";
}
/** 读取当前受限执行状态。 */
function readStatus(mode) {
	const supported = process.platform === "win32";
	const sandboxHome = defaultSandboxHome();
	const runnerReady = resolveRunnerExe() !== void 0;
	const setupExeReady = resolveSetupExe() !== void 0;
	const setupComplete = supported && sandboxSetupComplete(sandboxHome);
	const isolation = isolationOf(mode, supported, setupComplete);
	return {
		platform: process.platform,
		supported,
		mode,
		isolation,
		sandboxHome,
		runnerReady,
		setupExeReady,
		setupComplete,
		detail: detailOf(mode, isolation, runnerReady)
	};
}
/**
* 卸载提权档产物，使 `setupComplete` 回到 false。
* 只删 `<sandboxHome>` 下属于沙箱的条目，**不动** `~/.tpt-work` 其它内容；沙箱本地用户/组保留
* （删除它们需要管理员，且留着无害——R8 也不允许我在这里动账户）。
*/
function uninstallSandbox() {
	const sandboxHome = defaultSandboxHome();
	for (const entry of [
		".sandbox",
		".sandbox-secrets",
		".sandbox-bin",
		"cap_sid",
		"deny_read_acl_state.json"
	]) try {
		rmSync(join(sandboxHome, entry), {
			recursive: true,
			force: true
		});
	} catch {}
	return readStatus(sandboxMode());
}
/** 受限执行后端控制器（Remote 命名空间 `tptSandbox`）。 */
var TptSandboxController = class extends TypertRemoteService {
	/**
	* 条目 schema（rc.1 契约：**类插件**的表单来自 `static Config`，由 profile 条目按条目 id 投影）。
	* 内容与迁移前一字不改，只是换了家：`register(ns, schema, …)` 已退场 ⇒ schema 不再随注册调用送出，
	* 而是作为插件契约导出；段名 = 装配行 id（见 `packages/bundle/cordis.patch.yml` 的 `- id: tpt-sandbox`）。
	*/
	static Config = SandboxSettingsSchema;
	/** 设置作用域；宿主没有 settings 提供方时保持 undefined（档位退化为进程内）。 */
	scope;
	/** 无 settings 提供方时的退化落点（默认档）。 */
	modeFallback = "acl";
	/**
	* 注册服务、绑定 Gateway 命名空间，并（有 settings 提供方时）注册本插件的设置命名空间。
	* @param ctx - 宿主 context。
	*/
	constructor(ctx) {
		super(ctx, "tptSandbox", { namespace: "tptSandbox" });
		ctx.inject(["settings"], (settingsCtx) => {
			const settingsApi = settingsCtx.settings;
			this.scope = {
				get: () => settingsApi.describe().find((x) => String(x.ns) === "tpt-sandbox")?.value ?? {},
				update: (patch) => settingsApi.update(SETTINGS_NAMESPACE, patch)
			};
			this.applyMode(this.currentMode());
			settingsCtx.on("settings/document-updated", (ns) => {
				if (ns !== "tpt-sandbox") return;
				const mode = (settingsApi.describe().find((d) => String(d.ns) === SETTINGS_NAMESPACE)?.value)?.mode;
				if (mode === "acl" || mode === "elevated") setSandboxMode(mode);
			});
		});
	}
	/** 当前档位（设置优先，没有 settings 提供方时用进程内值）。 */
	currentMode() {
		return this.scope?.get().mode ?? this.modeFallback;
	}
	/** 把档位推进 `@tpt-work/sandbox`（进程内 + env + 状态文件）。 */
	applyMode(mode) {
		setSandboxMode(mode);
	}
	/** 读当前状态（顺带把设置里的档位同步进沙箱包——见模块头第 3 个推的时机）。 */
	status() {
		const mode = this.currentMode();
		this.applyMode(mode);
		return readStatus(mode);
	}
	/**
	* 切换档位。**只写设置，不装东西**：切到提权档后若 setup 未就绪，状态会显示
	* `not-installed` 并由 runner fail-closed，界面上再给「安装沙箱」按钮。
	*
	* ⚠ **危险 verb**（章节 H §1.3.4）：入口第一句是确认门，没有凭据时**连设置都不写**。档位是这台机器
	* 上「命令要不要被限制」的开关，而 wire 对已鉴权调用方全量开放 ⇒ 「谁都能一行 RPC 把受限执行关掉」
	* 是必须挡住的（浏览器半那道 `confirm` 在调用方手里，挡不住）。
	* @param request - 目标档位（+ 一次性确认凭据）。
	* @returns 切换后的状态。
	*/
	async setMode(request) {
		const mode = request.mode === "elevated" ? "elevated" : "acl";
		requireDangerConfirmation("tptSandbox", {
			verb: "setMode",
			subject: mode === "elevated" ? "提权（沙箱用户）" : "ACL（非提权，仅写限制）"
		}, request.confirm);
		if (this.scope === void 0) this.modeFallback = mode;
		else await this.scope.update({ mode });
		this.applyMode(mode);
		return readStatus(this.currentMode());
	}
	/**
	* 安装（启用）**提权档**需要的一次性 setup：跑一次提权 setup（弹 UAC）。已就绪时幂等空操作。
	*
	* ⚠ 方法名**不能叫 `install`**：客户端把每个命名空间挂成 `RemoteNamespaceService`，它的原型上
	* 已有 `install`（挂方法用）⇒ `assertMethodAvailable` 会判「与命名空间服务冲突」并拒绝整个贡献
	* （真机症状：整页 `Failed to load plugins`）。故用 `installSandbox`。
	*
	* ⚠ **异步**：UAC 应答与提权 setup 执行可能长达数分钟，等待分支已下放 koffi 线程池
	* （`shellExecuteRunas`），本方法返回 Promise；backend 事件循环在等待期间继续服务其余请求。
	*
	* 引导/插件卡片**未必有工作区**（首屏「选择工作区」还没选）⇒ 缺省用 `sandboxHome` 当锚点、
	* 且**不授任何写根**：工作区写 ACE 由 `AclWriteGrant.add(path)` 在命令真正跑起来时按工作区补授，
	* 这里凭空授一个写根只会把隔离开在错误的目录上。
	* @param request - 触发安装的工作区（可选；作为 setup 的读写根）+ 一次性确认凭据。
	* @returns 安装后的状态（Promise）。
	*/
	async installSandbox(request) {
		const sandboxHome = defaultSandboxHome();
		const workspaceRoot = request.workspaceRoot;
		requireDangerConfirmation("tptSandbox", {
			verb: "installSandbox",
			subject: `安装提权档 setup（会请求一次管理员授权）；读写根：${workspaceRoot ?? "未指定（只建沙箱宿主根）"}`
		}, request.confirm);
		await ensureSandboxSetup({
			sandboxHome,
			commandCwd: workspaceRoot ?? sandboxHome,
			readRoots: [workspaceRoot ?? sandboxHome],
			writeRoots: workspaceRoot === void 0 ? [] : [workspaceRoot],
			realUser: currentUserAccountName()
		});
		return readStatus(this.currentMode());
	}
	/**
	* 卸载提权档产物（ACL 档没有产物可卸；卸完提权档会回到 `not-installed`）。
	*
	* ⚠ 危险 verb：删的是那套提权 setup 产物（沙箱宿主根下的 runner / 账号相关产物），且**不可逆**——
	* 卸完想再用得重走一次管理员授权。所以入口第一句同样是确认门。
	* @param request - 一次性确认凭据。
	* @returns 卸载后的状态。
	*
	* ⚠ 形参**不许带默认值/解构/rest**：typert 网关注册 SRC 方法时按这条判形状，带默认值会当场拒
	* （真机症状：`tptSandbox/uninstall: SRC method "uninstall" must use unique identifier parameters
	* without destructuring, defaults, or rest` —— 卸载按钮必红）。调用方一律显式传对象
	* （客户端那条就是 `confirm === undefined ? {} : { confirm }`）。
	*/
	uninstall(request) {
		requireDangerConfirmation("tptSandbox", {
			verb: "uninstall",
			subject: "卸载提权档 setup 产物（之后要用得重新申请一次管理员授权）"
		}, request.confirm);
		return uninstallSandbox();
	}
	/**
	* 确认回路的**应答位**（第一方渲染端专用；章节 H §1.3.4）。
	*
	* 命名空间各挂一条是框架决定的：Gateway 只 route 本服务注册的方法，wire 上不存在"全局应答入口"。
	* 它调的是 `@tpt-work/danger-verbs` 那颗模块级单例，与另外两个命名空间的应答位同一颗 ⇒ 口径一份。
	* @param request - 待确认条目的 id（来自那次抛出的 details）+ 用户是否允许。
	* @returns 允许时的一次性凭据；拒绝或 id 已失效时 `undefined`。
	*/
	confirmDanger(request) {
		return answerDangerConfirmation(request.id, request.approve);
	}
};
/**
* 手动登记一个 Remote 方法——**等价于编译后的 `@Remote()`**。
*
* 本包构建链（tsdown/oxc）不转译标准装饰器语法（实测会把 `@Remote(...)` 原样留在产物里 ⇒ 语法错），
* 故按 dsh 编译产物（`__esDecorate` + `__runInitializers(this, …)`）的运行时形态手工复刻：`Remote(name)`
* 返回装饰器，喂一个合成 context 让它挂 initializer。
*
* ⚠ initializer 的 `this` 必须是**实例**（编译产物在构造器里 `__runInitializers(this, …)` 调用）：
* 装饰器内部取 `Object.getPrototypeOf(this)` 作为落点。早先误传 `prototype` 本身 ⇒ 标记落到
* `TypertRemoteService.prototype`（父类），而 Gateway 的 `remoteMethods(service)` 只读**本类**原型
* ⇒ 该命名空间零方法、`/api/tptSandbox/*` 一律 404（真机症状：设置页整节空白、引导按钮无反应）。
* @param prototype - 服务类原型。
* @param method - 公开实例方法名（同时是默认的 Remote 端点名）。
*/
function remoteMethod(prototype, method) {
	const context = {
		kind: "method",
		name: method,
		static: false,
		private: false,
		metadata: void 0,
		access: {
			has: () => true,
			get: (target) => Reflect.get(target, method)
		},
		addInitializer: (initializer) => {
			initializer.call(Object.create(prototype));
		}
	};
	Remote(method)(Reflect.get(prototype, method), context);
}
remoteMethod(TptSandboxController.prototype, "status");
remoteMethod(TptSandboxController.prototype, "setMode");
remoteMethod(TptSandboxController.prototype, "installSandbox");
remoteMethod(TptSandboxController.prototype, "uninstall");
remoteMethod(TptSandboxController.prototype, "confirmDanger");
