/**
 * 档位 → **runner 入口**的分派（implementation/sandbox-decodex-rename-acl-elevated-modes W4）。
 *
 * 消费点是 `dsh-sandbox-local` 里被本仓补丁改掉的那一处（
 * `patches/@deepseek-ai__dsh-sandbox-local.patch`）：seam 每次组装受限 argv 都来问本包要
 * 「用什么可执行体包裹这条命令」，于是档位只需在本包这一侧决定，seam 保持哑：
 *
 *  - `acl`（默认）⇒ **上游官方 runner**（`@deepseek-ai/dsh-sandbox-windows-acl/runner`），
 *    前面套一枚我方的**控制台垫片**（`./acl-launcher`，build 产物在位才套）。
 *    需求方口径「ACL 直接 import dsh 库」在这里做成真的：WRITE_RESTRICTED token、能力 SID 交集、
 *    stdio 形状、job 对象回收全是上游实现；垫片只做一件与隔离无关的事——在**未受限**时给 runner
 *    分配一个隐藏控制台，让受限子进程**继承**而不是在受限令牌下新建 conhost
 *    （桌面壳是 GUI 子系统的 Electron，链上没有控制台可继承；成因与对照读数见 `acl-launcher.ts` 头注）。
 *  - `elevated` ⇒ 我方 runner（帧 IPC + 以沙箱用户 `CreateProcessWithLogonW` 拉起），
 *    build 产物在位用产物，否则 dev 用 `--import tsx` 跑源文件（与补丁旧行为一致）。
 *
 * ⚠ 返回 `undefined` = 「seam 你自己按默认来」，而它的默认正是上游 runner ⇒ ACL 档连不上上游
 * 时不会静默换成我方路径（那等于用户选了 ACL 却跑到提权档上），而是维持上游语义。
 * @module @tpt-work/sandbox/entry
 */

import { existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { sandboxMode } from './mode.ts'

/** 上游 ACL 沙箱包（ACL 档的 runner 与 SID/授权语义都归它）。 */
const UPSTREAM_PACKAGE = '@deepseek-ai/dsh-sandbox-windows-acl'

/** 解析一个裸 specifier 到文件路径；解析不了（包不在）返回 undefined。 */
function resolveSpecifier(specifier: string): string | undefined {
  try {
    return fileURLToPath(import.meta.resolve(specifier))
  } catch {
    return undefined
  }
}

/** 我方控制台垫片（build 产物在位才用；缺席 ⇒ 退回原形 `[execPath, runner]`）。 */
function consoleShimPath(): string | undefined {
  const shim = resolveSpecifier('@tpt-work/sandbox/acl-launcher')
  return shim !== undefined && existsSync(shim) ? shim : undefined
}

/** ACL 档：上游官方 runner（可套我方控制台垫片）。上游缺席 ⇒ undefined（交回 seam 的默认，同一目标）。 */
function upstreamInvocation(): readonly string[] | undefined {
  const built = resolveSpecifier(`${UPSTREAM_PACKAGE}/runner`)
  if (built === undefined || !existsSync(built)) return undefined
  const shim = consoleShimPath()
  // 垫片把 runner 入口当**自己的 argv[1]** 收下，再在本进程里 import 它（argv 还原成直跑形态）。
  return shim === undefined ? [process.execPath, built] : [process.execPath, shim, built]
}

/** 提权档：本包 runner（build 产物优先，dev 退回 `src/runner.ts` + tsx loader）。 */
function elevatedInvocation(): readonly string[] {
  const built = resolveSpecifier('@tpt-work/sandbox/runner')
  if (built !== undefined && existsSync(built)) return [process.execPath, built]
  const source = resolveSpecifier('@tpt-work/sandbox/src/runner.ts') ?? 'src/runner.ts'
  return [process.execPath, '--import', 'tsx', source]
}

/**
 * seam 唯一问的那个函数：当前档位下包裹一条受限命令的 argv 前缀。
 * @returns `[execPath, …入口旗标]`；ACL 档且上游不可用时 `undefined`（seam 走它自己的默认）。
 */
export function sandboxRunnerInvocation(): readonly string[] | undefined {
  return sandboxMode() === 'elevated' ? elevatedInvocation() : upstreamInvocation()
}
