/**
 * 沙箱 runner 脚本入口：消费者 spawn 的 argv 包裹本体（**只服务提权档**，implementation/sandbox-decodex-rename-acl-elevated-modes W4：ACL 档下
 * seam 拿到的入口是上游官方 runner，本文件根本不会被 spawn；选它的那条路在 `entry.ts`）。
 *
 * argv 约定与上游 windows-acl runner 同款：`[node, runner.mjs, --workspace, …, --temp, …,
 * --mode, …, --, …argv]`。运行时可独立作为脚本执行：解析 flag → 建字节模式管道 →
 * 进程内 FFI（koffi）直接驱动 sandbox-runner.exe → 把 output 帧写到本进程 stdout、exit 帧映射为
 * 退出码。runner 缺位或 setup 未就绪都 fail-closed。
 * @module
 */

import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { mapSandboxProfile } from './profile.ts'
import { closeStdinFrame, frameDecoder, spawnRequestFrame, stdinFrame, terminateFrame, type SpawnRequest } from './ipc.ts'
import { defaultSandboxHome, resolveRunnerExe } from './paths.ts'
import { closeHandles, createPipePair, startReadLoop, toWire, waitForConnections, writeWire } from './ffi.ts'
import { sandboxSetupComplete } from './sandbox-users.ts'
import { readOnlyCapSidFromFile, workspaceWriteCapSid } from './cap-sids.ts'
import { materializeRunnerForSandbox, offlineSandboxCredential, pipeSecurityAttributes, spawnRunnerAsSandboxUser } from './elevated.ts'
import { terminateProcess } from './win32.ts'

async function main(): Promise<number> {
  // `--write-sid` / `--temp-write-sid` 由 seam 照旧传入，提权档用不上（它用 setup 落盘的 cap_sid），
  // 但**必须继续解析**——解析器不认识旗标就会把它当成命令 argv 的一部分喂下去。
  const { mode, workspace, command, temp, timeoutMs } = parseFlags(process.argv.slice(2))
  if (command.length === 0) {
    process.stderr.write('[tpt-sandbox] no command to run\n')
    return 1
  }

  // FFI 驱动需要 sandbox-runner.exe（postinstall 下载到安装位）。
  const runnerExe = resolveRunnerExe()
  if (runnerExe === undefined) {
    process.stderr.write('[tpt-sandbox] sandbox-runner.exe not installed; refusing to run unconfined\n')
    return 1
  }

  const sandboxHome = defaultSandboxHome()

  // implementation/sandbox-decodex-rename-acl-elevated-modes W4：本 runner **只服务提权档**。ACL 档下 seam 拿到的入口是上游官方 runner
  // （`entry.ts` 按档位分派），根本不会走到这里 ⇒ 这里不再有「非提权」分支，也就杜绝了
  // 「用户选了提权档、实际静默跑在无写隔离路径上」这种降级。setup 未就绪 ⇒ fail-closed 并指路。
  if (!sandboxSetupComplete(sandboxHome)) {
    process.stderr.write(
      `[tpt-sandbox] 提权档需要一次性 setup，但 ${sandboxHome} 下产物未就绪；拒绝降级执行。\n`
      + '   -> 设置 · 沙箱 里点「安装沙箱」（一次 UAC 授权），或把档位切回默认的 ACL 档。\n',
    )
    return 1
  }

  const profileMapping = mapSandboxProfile(mode, workspace, temp)
  // 提权路径必须用 **上游 setup 自己派生的能力 SID**（`<沙箱宿主根>/cap_sid`）——setup 把写 ACE
  // 授给的就是它，受限 token 的 restricting SID 交集才命中；拿不到即 fail-closed（否则
  // workspace-write 连工作区都写不了、read-only 的断言也没有意义）。
  // seam 传来的 `--write-sid` 是 dsh 侧的 `S-1-4-…` 能力 SID，**在这里用不上**：它对提权档的
  // 那份 DACL 没有任何授权，两档的信任主体不同（research/sandbox-decodex-rename-and-acl-elevated-modes §6 R5）。
  const capSid = mode === 'workspace-write'
    ? workspaceWriteCapSid(sandboxHome, workspace, workspace)
    : readOnlyCapSidFromFile(sandboxHome)
  if (capSid === undefined) {
    process.stderr.write(`[tpt-sandbox] 提权路径需要 ${sandboxHome}/cap_sid 里的能力 SID，缺失；拒绝运行\n`)
    return 1
  }
  const env = minimalEnv(workspace, temp)
  // 两种调用模式自动兼容（实测判据）：dsh 的两条 spawn 路径给 runner 的 stdio 不同——
  //  - 一次性 shell 工具（`dsh-pwsh-sandbox.runArgv/startArgv`）= per-stream 管道 ⇒ isTTY undefined；
  //  - 持久 shell / 终端（`dsh-terminal-bash` → `subprocess.spawnTerminal`，node-pty）= PTY ⇒ isTTY true。
  // 故按 runner 自身 stdio 决定 codex 侧 `tty`/`stdin_open`：终端模式让 codex 建**内置 ConPTY**
  // （沙箱内进程拿到真 TTY），管道模式保持纯字节输出（工具解析不被 ANSI 污染）。
  // ⚠ `stdin_open` 必须与 `tty` 同开：实测 tty:true + stdin_open:false ⇒ ConPTY 建成但无输出、
  //    退出码 0xC000013A(STATUS_CONTROL_C_EXIT)。
  const ptyMode = process.stdin.isTTY === true || process.stdout.isTTY === true
  const request: SpawnRequest = {
    command,
    cwd: workspace,
    env,
    permission_profile: profileMapping.permission_profile,
    workspace_roots: profileMapping.workspace_roots,
    // codex 侧提权路径把 SpawnRequest.codex_home 设为 `<codex_home>/.sandbox`（runner 仅用作 log_dir），
    // real_codex_home 才是真实宿主根（elevated_impl.rs L187）。
    codex_home: join(sandboxHome, '.sandbox'),
    real_codex_home: sandboxHome,
    cap_sids: [capSid],
    tty: ptyMode,
    stdin_open: ptyMode,
    use_private_desktop: false,
  }
  // timeout 契约（SpawnRequest.timeout_ms，2026-09-13 评审 medium：废除 120s 硬编码 race）：
  //  - 未传（或非正数）⇒ 不写该字段：codex 侧与本地 race 双双不限时（长命令/持久终端不再被击杀）；
  //  - 持久终端（PTY）一律不设：终端会话生命周期由用户控制，任何超时都不适用；
  //  - 一次性命令且 >0 ⇒ 写入 SpawnRequest，并以此值启用本地 race 兜底（见 raceWithTimeout）。
  const armedTimeoutMs = !ptyMode && timeoutMs !== undefined && Number.isFinite(timeoutMs) && timeoutMs > 0
    ? timeoutMs
    : undefined
  if (armedTimeoutMs !== undefined) request.timeout_ms = armedTimeoutMs

  // 建字节模式管道 → 以沙箱用户拉起 runner（连上来）→ 等连接 → 发 SpawnRequest。
  // 提权档恒走 `CreateProcessWithLogonW` 那条分支：管道 DACL 必须**同时**授给沙箱用户与当前用户
  // （父进程要连得上、子进程要写得了），这正是 `pipeSecurityAttributes(username)` 存在的理由。
  const credential = offlineSandboxCredential(sandboxHome)
  const pair = createPipePair('tpt-sandbox', pipeSecurityAttributes(credential.username))
  const args = [`--pipe-in=${pair.pipeInPath}`, `--pipe-out=${pair.pipeOutPath}`]
  const sandboxExe = materializeRunnerForSandbox(sandboxHome, runnerExe)
  // runner 的 cwd 用**命令的工作区**（上游 `spawn_runner_transport(home, cwd, …)` 同口径）：
  // 沙箱用户对工作区有 ACL，对沙箱宿主根所在路径未必可遍历。
  const handle = spawnRunnerAsSandboxUser(sandboxExe, args, credential, workspace)
  const killRunner = (): void => terminateProcess(handle.hProcess)
  // 等连接到点 fail-loud（overlapped + 有限等待，runner 未连入 → 抛错 → 下方 catch 分支 exit 1）。
  await waitForConnections(pair)
  writeWire(pair, toWire(spawnRequestFrame(request)))

  const decoder = frameDecoder()
  let exitCode = 1
  let sawReady = false
  let settle: (value: number) => void = () => {}
  const settled = new Promise<number>((resolve) => {
    settle = resolve
  })

  const stopRead = startReadLoop(
    pair.hOut,
    (chunk) => {
      for (const frame of decoder.feed(chunk)) {
        if (frame.type === 'spawn_ready') sawReady = true
        else if (frame.type === 'output') process.stdout.write(frame.data)
        else if (frame.type === 'exit') {
          exitCode = frame.exit_code
          settle(exitCode)
        } else if (frame.type === 'error') {
          process.stderr.write(`[tpt-sandbox] runner error: ${frame.message}\n`)
          settle(1)
        }
      }
    },
    () => settle(exitCode),
  )

  // 把本进程 stdin 转成 codex Stdin 帧（spawn_ready 后）；信号转 Terminate 帧。
  const wire = (json: string): void => writeWire(pair, toWire(json))
  if (process.stdin.isTTY && !process.stdin.isRaw) {
    try { process.stdin.setRawMode(true) } catch { /* 非 TTY 忽略 */ }
  }
  process.stdin.on('data', (d: Buffer) => {
    if (sawReady) wire(stdinFrame(d))
  })
  process.stdin.on('end', () => {
    if (sawReady) wire(closeStdinFrame())
  })
  const onSigterm = (): void => wire(terminateFrame())
  process.on('SIGTERM', onSigterm)
  process.on('SIGINT', onSigterm)

  // 本地超时 race 只在 armedTimeoutMs 存在时启用；未传 = 不限（直接等 settled）。
  const result = await raceWithTimeout(settled, armedTimeoutMs, () => {
    process.stderr.write(`[tpt-sandbox] 命令超过 timeout_ms=${String(armedTimeoutMs)}，kill runner\n`)
    stopRead()
    killRunner()
  })
  stopRead()
  closeHandles(pair)
  killRunner()
  return result
}

/**
 * 本地超时 race（2026-09-13 评审 medium：120s 硬编码改为 SpawnRequest.timeout_ms 契约）。
 * `timeoutMs === undefined` 时不限时直接等 settled；到点执行 onTimeout（停读 + kill runner）
 * 并以退出码 1 结束。竞速结束后清除定时器，未触发的超时不再拖住事件循环。
 */
export async function raceWithTimeout(
  settled: Promise<number>,
  timeoutMs: number | undefined,
  onTimeout: () => void,
): Promise<number> {
  if (timeoutMs === undefined) return settled
  let timer: ReturnType<typeof setTimeout> | undefined
  try {
    return await Promise.race([
      settled,
      new Promise<number>((resolve) => {
        timer = setTimeout(() => {
          onTimeout()
          resolve(1)
        }, timeoutMs)
      }),
    ])
  } finally {
    if (timer !== undefined) clearTimeout(timer)
  }
}

/**
 * codex SpawnRequest 需要的最小环境。
 * ⚠ `--temp` 存在时 TEMP/TMP 指向私有 temp 目录（2026-09-13 评审 medium：此前一律指向工作区，
 * per-session temp 隔离被静默降级）；未传时维持原状（工作区）。
 */
function minimalEnv(workspace: string, temp?: string | undefined): Record<string, string> {
  const systemRoot = process.env.SystemRoot ?? 'C:\\Windows'
  const tempDir = temp ?? workspace
  return {
    SystemRoot: systemRoot,
    windir: process.env.windir ?? systemRoot,
    ComSpec: process.env.ComSpec ?? `${systemRoot}\\System32\\cmd.exe`,
    'PATHEXT': '.COM;.EXE;.BAT;.CMD',
    'PATH': process.env.PATH ?? `${systemRoot}\\System32`,
    TEMP: tempDir,
    TMP: tempDir,
  }
}

function parseFlags(args: string[]): { mode: Parameters<typeof mapSandboxProfile>[0]; workspace: string; temp?: string | undefined; writeSid?: string | undefined; tempWriteSid?: string | undefined; timeoutMs?: number | undefined; command: string[] } {
  const out: { mode: Parameters<typeof mapSandboxProfile>[0]; workspace: string; temp?: string | undefined; writeSid?: string | undefined; tempWriteSid?: string | undefined; timeoutMs?: number | undefined; command: string[] } = {
    mode: 'read-only',
    workspace: process.cwd(),
    command: [],
  }
  let i = 0
  while (i < args.length) {
    const a = args[i]!
    if (a === '--') {
      out.command = args.slice(i + 1)
      break
    }
    if (a === '--mode') out.mode = (args[++i] === 'workspace-write' ? 'workspace-write' : 'read-only')
    else if (a === '--workspace') out.workspace = args[++i] ?? out.workspace
    else if (a === '--temp') out.temp = args[++i]
    else if (a === '--write-sid') out.writeSid = args[++i]
    else if (a === '--temp-write-sid') out.tempWriteSid = args[++i]
    else if (a === '--timeout-ms') {
      const n = Number(args[++i])
      // 非法值按「未传」处理（= 不限时），不静默抛错也不猜默认值。
      out.timeoutMs = Number.isFinite(n) ? n : undefined
    }
    i += 1
  }
  return out
}

// 作为脚本被 spawn 时直接执行；被 import（单测）时导出 parseFlags 不自动跑。
const selfEntry = fileURLToPath(import.meta.url)
const isMain = process.argv[1] !== undefined && fileURLToPath(new URL(`file://${process.argv[1]}`)) === selfEntry
if (isMain) {
  // end(cb) 先冲刷已排队输出（output 帧先于 exit 帧，保证不丢）再显式退出。
  // catch 分支：waitForConnections 到点 fail-loud 抛错等失败路径 → stderr 明确报错 + exit 1，
  // 不落成 unhandled rejection（2026-09-13 评审 low 项顺带收口）。
  void main().then(
    (code) => {
      process.stdout.end(() => process.exit(code))
    },
    (err: unknown) => {
      process.stderr.write(`[tpt-sandbox] runner 失败：${err instanceof Error ? err.message : String(err)}\n`)
      process.exit(1)
    },
  )
}

export { parseFlags, minimalEnv, main }
