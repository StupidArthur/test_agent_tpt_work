/**
 * `@tpt-work/sandbox` —— TPT 的**受限执行后端**，两档。
 *
 * dsh 的沙箱 seam（`@deepseek-ai/dsh-sandbox-local`）在 Windows 上只有一个落点 `windows-acl`，
 * 它问本包要四样东西：`AclWriteGrant` / `workspaceWriteSid` / `tempWriteSid` /
 * `assertTempRootOutsideWorkspace`，外加「用什么可执行体包裹这条命令」（`sandboxRunnerInvocation()`）。
 * 绑定见 `patches/@deepseek-ai__dsh-sandbox-local.patch` —— 那是本仓唯一的解析劫持（本仓没有 pnpm
 * override，`patchedDependencies` 才是）。
 *
 * 两档由设置项 `tpt-sandbox.mode` 决定，**默认 `acl`**：
 *
 *  | 档 | 写隔离靠什么 | 谁在热路径上 |
 *  |---|---|---|
 *  | `acl`（默认） | WRITE_RESTRICTED token 与能力 SID ACE 的交集 | **上游 `@deepseek-ai/dsh-sandbox-windows-acl`**：SID、授权、runner 全是它的 |
 *  | `elevated` | 命令跑在另一个低权本地用户的 token 上 | 本包：帧 IPC + `sandbox-runner.exe` + `CreateProcessWithLogonW` |
 *
 * 所以本包的定位 = 「**提权档的实现 + 两档的分派门面**」。ACL 档下我方一行代码都不在受限执行的
 * 热路径上（`entry.ts` 把 seam 直接指到上游 runner，`grant.ts` 的 `AclWriteGrant` 把上游实例原样
 * 交回，`workspace-sid.ts` / `path-boundary.ts` 转发上游）：不提权、不要 UAC、装完即用；代价是它
 * 只限**写**（读、网络、进程可见性都不限），界面必须照实说，不许写得像提权档一样强。
 *
 * 提权档才用得到本包剩下的那一整套：`setup.ts`（一次 UAC 跑上游 setup 产出沙箱用户凭据）+
 * `elevated.ts`（以该用户拉起 runner + 双 ACE 管道 DACL）+ `runner.ts`/`ipc.ts`/`ffi.ts`（帧 IPC
 * 驱动）。runner 缺位一律 fail-closed，绝不静默不受限执行。
 *
 * ⚠ 两档各留一种**不会被回收**的常驻 ACE（trustee 不同：能力 SID vs 沙箱用户/组）。换档是加法
 * 不是替换 ⇒ 来回切会攒 ACE。已知边界，登记在 research/sandbox-decodex-rename-and-acl-elevated-modes。
 * @module @tpt-work/sandbox
 */

