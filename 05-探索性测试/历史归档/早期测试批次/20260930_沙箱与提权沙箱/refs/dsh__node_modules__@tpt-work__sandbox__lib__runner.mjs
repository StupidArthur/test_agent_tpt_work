const IPC_PROTOCOL_VERSION = 6;
/** 构造 spawn_request 顶层帧。 */
function spawnRequestFrame(request) {
	return JSON.stringify({
		version: IPC_PROTOCOL_VERSION,
		type: "spawn_request",
		payload: request
	});
}
/** 向子进程 stdin 写一帧（data 以 base64 编码）。 */
function stdinFrame(data) {
	return JSON.stringify({
		version: IPC_PROTOCOL_VERSION,
		type: "stdin",
		payload: { data_b64: Buffer.from(data).toString("base64") }
	});
}
/** 关闭子进程 stdin（EOF）。 */
function closeStdinFrame() {
	return JSON.stringify({
		version: IPC_PROTOCOL_VERSION,
		type: "close_stdin",
		payload: {}
	});
}
/** 终止子进程。 */
function terminateFrame() {
	return JSON.stringify({
		version: IPC_PROTOCOL_VERSION,
		type: "terminate",
		payload: {}
	});
}
/** 累积从 out 管道读到的字节并按帧边界切分。 */
function frameDecoder() {
	let buf = Buffer.alloc(0);
	return {
		feed(chunk) {
			buf = Buffer.concat([buf, chunk]);
			const frames = [];
			for (;;) {
				if (buf.length < 4) break;
				const len = buf.readUInt32LE(0);
				if (buf.length < 4 + len) break;
				const json = buf.subarray(4, 4 + len).toString("utf8");
				buf = buf.subarray(4 + len);
				const parsed = JSON.parse(json);
				const p = parsed.payload;
				if (parsed.type === "spawn_ready") frames.push({
					type: "spawn_ready",
					process_id: p?.process_id ?? 0
				});
				else if (parsed.type === "output" && p?.data_b64 !== void 0) frames.push({
					type: "output",
					data: Buffer.from(p.data_b64, "base64"),
					stream: p.stream === "stderr" ? "stderr" : "stdout"
				});
				else if (parsed.type === "exit") frames.push({
					type: "exit",
					exit_code: p?.exit_code ?? 0,
					timed_out: p?.timed_out ?? false
				});
				else if (parsed.type === "error") {
					const errorFrame = {
						type: "error",
						message: p?.message ?? "(no message)"
					};
					if (p?.stage !== void 0) errorFrame.stage = p.stage;
					if (p?.windows_error_code !== void 0) errorFrame.windows_error_code = p.windows_error_code;
					frames.push(errorFrame);
				}
			}
			return frames;
		},
		remainder() {
			return buf;
		}
	};
}
