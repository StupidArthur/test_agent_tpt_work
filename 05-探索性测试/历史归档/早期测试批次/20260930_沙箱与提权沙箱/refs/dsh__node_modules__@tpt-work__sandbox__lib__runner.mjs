const READ_ONLY_SPECIALS = [
	{ kind: "root" },
	{ kind: "project_roots" },
	{ kind: "slash_tmp" },
	{ kind: "tmpdir" },
	{ kind: "minimal" }
];
/**
* dsh 模式 → codex PermissionProfile + cap_sids。cap_sid 直接用 dsh 能力 SID
* （`workspaceWriteSid` S-1-4-… 或只读固定 SID）——映射「策略/能力 SID → cap_sids」。
* 工作区写由 workspaceRoot 显式给一个 write 条目 + 该工作区的能力 SID。
*
* ⚠ `privateTemp`（dsh-sandbox-local `--temp` 旗标，2026-09-13 评审 medium）：workspace-write 下
* 私有 temp 目录也必须是 write 条目，否则 codex 拒写、per-session temp 能力静默失效；
* read-only **不加**（只读模式不得因 temp 旗标放松，fail-closed）。`--temp-write-sid` 是
* 调用方（seam）已物化 ACE 的透传语义，本映射不消费。
*/
function mapSandboxProfile(mode, workspaceRoot, privateTemp) {
	const fileSystemEntries = [];
	for (const value of READ_ONLY_SPECIALS) fileSystemEntries.push({
		path: {
			type: "special",
			value
		},
		access: "read"
	});
	if (mode === "workspace-write") {
		fileSystemEntries.push({
			path: {
				type: "path",
				path: workspaceRoot
			},
			access: "write"
		});
		if (privateTemp !== void 0) fileSystemEntries.push({
			path: {
				type: "path",
				path: privateTemp
			},
			access: "write"
		});
	}
	const permission_profile = {
		type: "managed",
		file_system: {
			type: "restricted",
			entries: fileSystemEntries
		},
		network: "restricted"
	};
	const capSid = mode === "workspace-write" ? workspaceWriteSid(workspaceRoot) : readOnlyCapSid();
	return {
		permission_profile,
		workspace_roots: mode === "workspace-write" ? [workspaceRoot] : [],
		cap_sids: [capSid]
	};
}
