/**
 * 把 dsh sandbox 的策略（mode/workspaceRoot）映射成 codex-command-runner 的
 * PermissionProfile + cap_sids（research/codex-command-runner-de-risked-no-isolation-non-elevated/030 契约）。
 *
 * cap_sid 直接用 dsh 能力 SID（`workspaceWriteSid` S-1-4-… 或只读固定 SID）——映射
 * 「策略/能力 SID → cap_sids」。写隔离由 runner 以另一低权用户 + ACL 实现（见 grant.ts / research/codex-elevated-sandbox-blueprint）。
 * @module
 */

import type { PermissionProfile } from './ipc.ts'
import { readOnlyCapSid, workspaceWriteSid } from './workspace-sid.ts'

/** dsh 沙箱模式（与 @deepseek-ai/dsh-sandbox 对齐，避免运行时依赖拉进纯类型）。 */
export type SandboxProfileMode = 'read-only' | 'workspace-write'

/** 一次映射的结果：交给 SpawnRequest 的 permission_profile / workspace_roots / cap_sids。 */
export interface SandboxProfileMapping {
  permission_profile: PermissionProfile
  workspace_roots: string[]
  cap_sids: string[]
}

const READ_ONLY_SPECIALS: Array<{ kind: 'root' | 'project_roots' | 'slash_tmp' | 'tmpdir' | 'minimal' }> = [
  { kind: 'root' },
  { kind: 'project_roots' },
  { kind: 'slash_tmp' },
  { kind: 'tmpdir' },
  { kind: 'minimal' },
]

/**
 * dsh 模式 → codex PermissionProfile + cap_sids。cap_sid 直接用 dsh 能力 SID
 * （`workspaceWriteSid` S-1-4-… 或只读固定 SID）——映射「策略/能力 SID → cap_sids」。
 * 工作区写由 workspaceRoot 显式给一个 write 条目 + 该工作区的能力 SID。
 *
 * ⚠ `privateTemp`（dsh-sandbox-local `--temp` 旗标，2026-09-13 评审 medium）：workspace-write 下
 * 私有 temp 目录也必须是 write 条目，否则 codex 拒写、per-session temp 能力静默失效；
 * read-only **不加**（只读模式不得因 temp 旗标放松，fail-closed）。`--temp-write-sid` 是
 * 调用方（seam）已物化 ACE 的透传语义，本映射不消费。
 */
export function mapSandboxProfile(
  mode: SandboxProfileMode,
  workspaceRoot: string,
  privateTemp?: string | undefined,
): SandboxProfileMapping {
  const fileSystemEntries: PermissionProfile['file_system']['entries'] = []
  for (const value of READ_ONLY_SPECIALS) {
    fileSystemEntries.push({ path: { type: 'special', value }, access: 'read' })
  }
  if (mode === 'workspace-write') {
    fileSystemEntries.push({ path: { type: 'path', path: workspaceRoot }, access: 'write' })
    if (privateTemp !== undefined) {
      fileSystemEntries.push({ path: { type: 'path', path: privateTemp }, access: 'write' })
    }
  }
  const permission_profile: PermissionProfile = {
    type: 'managed',
    file_system: { type: 'restricted', entries: fileSystemEntries },
    network: 'restricted',
  }
  const capSid = mode === 'workspace-write' ? workspaceWriteSid(workspaceRoot) : readOnlyCapSid()
  const workspace_roots = mode === 'workspace-write' ? [workspaceRoot] : []
  return { permission_profile, workspace_roots, cap_sids: [capSid] }
}
