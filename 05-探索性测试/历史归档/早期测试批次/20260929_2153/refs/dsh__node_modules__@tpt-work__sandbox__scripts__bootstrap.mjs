/**
 * TPT tpt-sandbox postinstall 引导：把 codex 官方两个二进制取到 `~/.tpt-work/sandbox/`
 * （或 `TPT_SANDBOX_ROOT` 覆写的落点）：
 *  - `sandbox-runner.exe` —— 每命令受限执行（非提权路径 / 提权路径的子进程宿主）。
 *  - `sandbox-setup.exe`  —— 一次性提权 setup（建沙箱用户 + 写 DPAPI 凭据 + ACL，research/codex-elevated-sandbox-blueprint）。
 *
 * **唯一声明位** = `../src/sandbox-binary-lock.json`：release pin / 资产名 / 落盘名 / 字节数 /
 * 体量下限 / 源基址 / sha256 全部直读该 JSON，本文件零字面量副本（postinstall 先于 build ⇒
 * 直读 src、绝不依赖构建产物）。运行期消费方 `src/binaries.ts` 读同一份；下载逻辑因
 * 「postinstall 吃不到 lib/」而两侧各一份，值由根门禁
 * `tests/quality/sandbox-binary-lock-single-source.spec.ts` 钉同源
 * （账本 `implementation/imp-adopt-upstream-copy-batch` 章节 B）。
 *
 * 落盘判据 = 按 lock 复算 sha256（与 binaries.ts 同规则）：在位件体量相等且摘要一致即幂等
 * 跳过；否则 `*.tmp` 唯一命名写入 → 流式复算 → `rename` 原子落位。重定向只手工跟 ≤5 跳，
 * http 目标必须与首发同 host。一切失败分支删半写 tmp、不动在位件。离线/网络失败容忍
 * （不阻断 install；运行期 resolveRunnerExe / resolveSetupExe 找不到即 fail-closed）。
 *
 * main 有 `import.meta.main` 守卫：被测试 import（tests/bootstrap-lock.spec.ts 注入假源与
 * mkdtemp 落点）不触发下载；实际经 postinstall 由 pnpm 安装本包时执行
 * （node scripts/bootstrap.mjs）。
 */
import { createHash, randomBytes } from 'node:crypto'
import { createWriteStream, mkdirSync, openSync, readSync, closeSync, renameSync, rmSync, statSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'node:path'
import { get as httpGet } from 'node:http'
import { get as httpsGet } from 'node:https'
import lock from '../src/sandbox-binary-lock.json' with { type: 'json' }

// 构建机（CI runner 以 SYSTEM 跑）用 TPT_SANDBOX_ROOT 把落点挪出系统账户目录（ci/setup.ps1 指到
// E: 盘持久缓存，跨 job 复用）；开发机 postinstall 不设该 env ⇒ 行为不变（~/.tpt-work/sandbox）。
const DEST = process.env.TPT_SANDBOX_ROOT ?? join(homedir(), '.tpt-work', 'sandbox')

/** 手工跟跳上限（与 binaries.ts 同规则）。 */
const MAX_REDIRECTS = 5

/** lock.sources 派生的源基址清单（优先序不变）；镜像 env 缝在位则整体替换 mirror 那颗（与 binaries.ts 同缝同名 ⇒ 根门禁钉）。 */
export function basesFromLock() {
  const override = process.env.TPT_SANDBOX_MIRROR_BASE
  return lock.sources.map((source) => (source.kind === 'mirror' && override !== undefined && override !== '' ? override : source.base))
}

/** 全文件 sha256（流式分块读）；读不了 ⇒ null。 */
export function sha256OfFile(file) {
  try {
    const hash = createHash('sha256')
    const fd = openSync(file, 'r')
    try {
      const buf = Buffer.alloc(1 << 20)
      for (;;) {
        const read = readSync(fd, buf, 0, buf.length, null)
        if (read === 0) break
        hash.update(buf.subarray(0, read))
      }
    } finally {
      closeSync(fd)
    }
    return hash.digest('hex')
  } catch {
    return null
  }
}

/** lock 的落盘判据：`bytes` 体量预检 + 全文件 sha256 全等（与 binaries.ts 的 matchesLock 同一把尺）。 */
export function matchesLock(file, entry) {
  try {
    if (statSync(file).size !== entry.bytes) return false
  } catch {
    return false
  }
  return sha256OfFile(file) === entry.sha256
}

/**
 * 单次下载流式写 `tmp`（绝不直接写 dest）。内网 nexus 镜像走 http://、GitHub 回退走 https://
 * ——按协议分派请求模块（node:https.get 不接受 http: URL）。3xx 手工跟 ≤hopsLeft 跳，
 * http 目标必须与首发同 host（拦 https→http 降级与任意异站跳转）。
 */
export function download(url, tmp, hopsLeft, originHost) {
  const request = url.startsWith('https:') ? httpsGet : httpGet
  return new Promise((resolve, reject) => {
    const req = request(url, { timeout: 120_000 }, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        res.resume()
        req.destroy()
        if (hopsLeft <= 0) {
          reject(new Error(`redirect limit (${MAX_REDIRECTS} hops) exceeded at ${url}`))
          return
        }
        let next
        try {
          next = new URL(res.headers.location, url)
        } catch {
          reject(new Error(`invalid redirect target ${res.headers.location} at ${url}`))
          return
        }
        if (next.protocol === 'http:' && next.host !== originHost) {
          reject(new Error(`redirect off-list (http redirect to foreign host): ${url} -> ${next.href}`))
          return
        }
        download(next.href, tmp, hopsLeft - 1, originHost).then(resolve, reject)
        return
      }
      if (res.statusCode !== 200) {
        res.resume()
        reject(new Error(`download ${url} -> HTTP ${res.statusCode}`))
        return
      }
      const out = createWriteStream(tmp)
      res.pipe(out)
      out.on('finish', () => out.end(() => resolve()))
      res.on('error', reject)
      out.on('error', reject)
    })
    req.on('error', reject)
    req.on('timeout', () => req.destroy(new Error('download timeout')))
  })
}

/**
 * 确保一个二进制在落点就位且与 lock 摘要一致（幂等）。
 * 失败不抛：删半写 tmp、换下一源；全源败尽返回 false（离线容忍，不阻断 install）。
 * @param entry - lock 条目消费形状 `{file,dest,bytes,minSize,sha256}`（测试注入同形状夹具）。
 * @param options - `{bases,destDir}` 测试注入假源与隔离落点（R8）；默认 = lock.sources + env 缝、`DEST`。
 */
export async function ensureBinary(entry, options = {}) {
  const dir = options.destDir ?? DEST
  const destPath = join(dir, entry.dest)
  if (matchesLock(destPath, entry)) {
    // eslint-disable-next-line no-console
    console.log(`[tpt-sandbox] ${entry.dest} already present (sha256 matches lock); skipping download`)
    return true
  }
  mkdirSync(dir, { recursive: true })
  const bases = options.bases ?? basesFromLock()
  const tmp = join(dir, `${entry.dest}.tmp-${process.pid}-${randomBytes(4).toString('hex')}`)
  for (const base of bases) {
    const url = `${base.replace(/\/+$/u, '')}/${lock.assetPath}/${lock.release}/${entry.file}`
    let originHost
    try {
      originHost = new URL(url).host
    } catch {
      // eslint-disable-next-line no-console
      console.warn(`[tpt-sandbox] ${entry.dest}: base is not a valid URL, skipping: ${base}`)
      continue
    }
    try {
      await download(url, tmp, MAX_REDIRECTS, originHost)
      if (!matchesLock(tmp, entry)) {
        throw new Error(`sha256 mismatch for ${entry.dest} (expected ${entry.sha256}, actual ${sha256OfFile(tmp) ?? 'unreadable'} / ${statSyncSafe(tmp)} bytes)`)
      }
      renameSync(tmp, destPath)
      // eslint-disable-next-line no-console
      console.log(`[tpt-sandbox] downloaded ${entry.file} (${statSync(destPath).size} bytes) from ${url}`)
      return true
    } catch (error) {
      // 一切失败分支清半写 tmp（安装位不残留、在位件字节不变），带期望/实际摘要对账读数换下一源。
      rmSync(tmp, { force: true })
      // eslint-disable-next-line no-console
      console.warn(`[tpt-sandbox] download failed from ${url}: ${error instanceof Error ? error.message : String(error)}`)
    }
  }
  // offline/hard failure: 不阻断 install；运行期 resolveRunnerExe/resolveSetupExe 找不到即 fail-closed。
  // eslint-disable-next-line no-console
  console.warn(`[tpt-sandbox] ${entry.file} unavailable after postinstall; that path will fail closed`)
  return false
}

/** 体量读数（读不了 ⇒ -1，只服务于失败诊断文案）。 */
function statSyncSafe(file) {
  try {
    return statSync(file).size
  } catch {
    return -1
  }
}

async function main() {
  if (process.platform !== 'win32') return
  mkdirSync(DEST, { recursive: true })
  for (const f of lock.files) {
    await ensureBinary({ file: f.asset, dest: f.dest, bytes: f.bytes, minSize: f.minBytes, sha256: f.sha256 })
  }
}

