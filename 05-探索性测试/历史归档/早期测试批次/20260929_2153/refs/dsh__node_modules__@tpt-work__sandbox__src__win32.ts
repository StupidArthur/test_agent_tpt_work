export const SEE_MASK_NOCLOSEPROCESS = 0x00000040
export const SEE_MASK_NOASYNC = 0x00000100
export const SW_HIDE = 0

/**
 * 以 `runas`（UAC 提权）启动一个可执行文件并等待其结束。
 *
 * ⚠ **非阻塞契约**（2026-09-13 评审 medium）：UAC 应答与提权进程执行都可能长达数分钟，而本函数
 * 运行在 backend 单线程 Node 里。两段等待分支——ShellExecuteExW 的 UAC 阻塞、WaitForSingleObject
 * 的进程等待——都经 koffi `.async` 下放线程池（仓内先例：`ffi.ts` 输出读循环），事件循环全程不停摆。
 * 对外语义不变：UAC 取消/启动失败仍 reject（fail-closed），提权进程退出码仍是成功判据。
 *
 * 错误码说明：`.async` 回调在主线程执行，而 `GetLastError` 是 thread-local ⇒ worker 线程的
 * 原生错误码（如 UAC 取消 err=1223）取不回来；诊断改读 ShellExecuteExW 写回 `sei` 的
 * `hInstApp`（SE_ERR_* 值，落盘在共享内存里，主线程读取无 thread-local 问题）。
 *
 * @param exePath - 目标 exe 绝对路径（sandbox-setup.exe）。
 * @param parameters - 命令行参数（此处即 base64 payload）。
 * @param cwd - 工作目录。
 * @returns 子进程退出码（0 = 成功）的 Promise。
 * @throws 用户取消 UAC 或 ShellExecuteExW 失败（附 hInstApp）、等待分支出错时 reject。
 */
export function shellExecuteRunas(exePath: string, parameters: string, cwd: string): Promise<number> {
  return new Promise((resolve, reject) => {
    const sei = koffi.alloc('TPT_SHELLEXECUTEINFOW', 1)
    koffi.encode(sei, 'TPT_SHELLEXECUTEINFOW', {
      cbSize: koffi.sizeof('TPT_SHELLEXECUTEINFOW'),
      fMask: SEE_MASK_NOCLOSEPROCESS | SEE_MASK_NOASYNC,
      lpVerb: 'runas',
      lpFile: exePath,
      lpParameters: parameters,
      lpDirectory: cwd,
      nShow: SW_HIDE,
    })
    const shell32 = loadWin32Library('shell32.dll')
    const ShellExecuteExW = shell32.func('int ShellExecuteExW(TPT_SHELLEXECUTEINFOW* info)')
    // 等待分支 1：ShellExecuteExW 在 UAC 应答前阻塞——放线程池，主事件循环继续服务 wire/ws/agent 回合。
    ShellExecuteExW.async(sei, (execErr: unknown, execOk: unknown) => {
      if (execErr || !execOk) {
        const info = koffi.decode(sei, 'TPT_SHELLEXECUTEINFOW') as { hInstApp: unknown }
        reject(new Error(`ShellExecuteExW(runas) failed${execErr ? `: ${String(execErr)}` : ` hInstApp=${String(info.hInstApp)}（SE_ERR_*，含 UAC 取消）`}`))
        return
      }
      const info = koffi.decode(sei, 'TPT_SHELLEXECUTEINFOW') as { hProcess: unknown }
      if (!info.hProcess) {
        resolve(-1)
        return
      }
      const WaitForSingleObject = kernel32().func('uint WaitForSingleObject(void* h, uint ms)')
      const GetExitCodeProcess = kernel32().func('int GetExitCodeProcess(void* h, uint* code)')
      const codeBuf = koffi.alloc('uint32', 1)
      // 等待分支 2：提权 setup 进程的执行期（可达数分钟）——同样放线程池。
      WaitForSingleObject.async(info.hProcess, 0xffffffff, (waitErr: unknown) => {
        try {
          if (waitErr) {
            reject(new Error(`WaitForSingleObject(setup) failed: ${String(waitErr)}`))
            return
          }
          GetExitCodeProcess(info.hProcess, codeBuf)
          resolve(koffi.decode(codeBuf, 'uint32') as number)
        } finally {
          try { CloseHandleFn()(info.hProcess) } catch { /* 尽力而为 */ }
        }
      })
    })
  })
}

const CloseHandleFn = lazily(() => kernel32().func('int CloseHandle(void* h)'))

/** 结束一个进程句柄（提权 runner 的 kill 语义）。 */
export function terminateProcess(hProcess: unknown, code = 1): void {
  try {
    ;(kernel32().func('int TerminateProcess(void* h, uint code)') as (h: unknown, c: number) => number)(hProcess, code)
  } catch {
    /* 尽力而为 */
  }
}
