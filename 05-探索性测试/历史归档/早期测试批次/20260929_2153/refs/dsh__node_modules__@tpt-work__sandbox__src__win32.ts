const CreateProcessWithLogonWFn = lazily(() => advapi().func(
  'int CreateProcessWithLogonW(wchar_t* user, wchar_t* domain, wchar_t* password, uint32 logonFlags, wchar_t* appName, wchar_t* cmdLine, uint32 creationFlags, void* env, wchar_t* cwd, TPT_STARTUPINFOW* si, TPT_PROCESS_INFORMATION* pi)',
))

/** 以沙箱用户身份拉起进程的结果。 */
export interface LogonSpawnResult {
  pid: number
  hProcess: unknown
  hThread: unknown
}

/**
 * `CreateProcessWithLogonW` 以沙箱用户拉起进程（非提权父进程即可，前提是 setup 已完成）。
 * @param creds - 沙箱用户名与明文密码（由 `readSandboxUsers` 解出）。
 * @param commandLine - 完整命令行（含 exe 路径；该缓冲会被 API 就地改写，故传新串）。
 * @param cwd - 子进程工作目录。
 */
export function spawnAsSandboxUser(
  creds: { username: string; password: string },
  commandLine: string,
  cwd: string,
): LogonSpawnResult {
  const si = koffi.alloc('TPT_STARTUPINFOW', 1)
  // ⚠ 只设 cb、**不设 lpDesktop**（codex `runner_client.rs` 同款：si 全零 + cb）——沙箱用户是另一个
  // 登录会话，指定 `winsta0\default` 会让它连不到交互窗口站 ⇒ 子进程 STATUS_DLL_INIT_FAILED (0xC0000142)。
  koffi.encode(si, 'TPT_STARTUPINFOW', { cb: koffi.sizeof('TPT_STARTUPINFOW') })
  const pi = koffi.alloc('TPT_PROCESS_INFORMATION', 1)
  const ok = CreateProcessWithLogonWFn()(
    creds.username,
    '.',
    creds.password,
    LOGON_WITH_PROFILE,
    null,
    commandLine,
    CREATE_NO_WINDOW | CREATE_UNICODE_ENVIRONMENT,
    null,
    cwd,
    si,
    pi,
  )
  if (!ok) throw new Error(`CreateProcessWithLogonW failed err=${getLastError()}`)
  const out = koffi.decode(pi, 'TPT_PROCESS_INFORMATION') as { hProcess: unknown; hThread: unknown; dwProcessId: number }
  return { pid: out.dwProcessId, hProcess: out.hProcess, hThread: out.hThread }
}

/** 解析账户名 → SID 字符串（给管道 DACL 授沙箱用户用）。 */
export function lookupAccountSid(name: string): string {
  const Lookup = advapi().func('int LookupAccountNameW(wchar_t* system, wchar_t* account, void* sid, uint32* sidSize, wchar_t* domain, uint32* domSize, uint32* use)')
  const sidSize = koffi.alloc('uint32', 1)
  const domSize = koffi.alloc('uint32', 1)
  const use = koffi.alloc('uint32', 1)
  // 首次调用只为取所需缓冲大小（预期失败 ERROR_INSUFFICIENT_BUFFER=122）。
  Lookup(null, name, null, sidSize, null, domSize, use)
  const sidBytes = koffi.decode(sidSize, 'uint32') as number
  if (!sidBytes) throw new Error(`LookupAccountNameW(${name}) 未返回 SID 大小 err=${getLastError()}`)
  const sidBuf = koffi.alloc('uint8', sidBytes)
  const domBuf = koffi.alloc('uint16', (koffi.decode(domSize, 'uint32') as number) + 1)
  if (!Lookup(null, name, sidBuf, sidSize, domBuf, domSize, use)) {
    throw new Error(`LookupAccountNameW(${name}) failed err=${getLastError()}`)
  }
  // 直接按 SID 二进制布局解析，避开 ConvertSidToStringSidW 的 UTF-16 解码（koffi str16 处崩）。
  return sidBufferToString(koffi.decode(sidBuf, 'uint8', sidBytes) as Uint8Array)
}

/**
 * SID 二进制 → `S-1-5-21-…` 字符串。
 * 布局：byte0=Revision，byte1=SubAuthorityCount(N)，byte2..7=IdentifierAuthority（6 字节大端），
 * byte8..=SubAuthority[N]（各 4 字节小端）。
 */
function sidBufferToString(bytes: Uint8Array): string {
  const revision = bytes[0] ?? 0
  const count = bytes[1] ?? 0
  let authority = 0n
  for (let i = 0; i < 6; i++) authority = (authority << 8n) | BigInt(bytes[2 + i] ?? 0)
  const subs: number[] = []
  for (let i = 0; i < count; i++) {
    const o = 8 + i * 4
    subs.push(((bytes[o] ?? 0) | ((bytes[o + 1] ?? 0) << 8) | ((bytes[o + 2] ?? 0) << 16) | ((bytes[o + 3] ?? 0) << 24)) >>> 0)
  }
  return `S-${revision}-${authority}${subs.map((s) => `-${s}`).join('')}`
}

/** 从 SID 指针按二进制布局解析出 SID 字符串。 */
function sidPointerToString(sidPtr: unknown): string {
  const head = koffi.decode(sidPtr, 'uint8', 8) as Uint8Array
  const count = head[1] ?? 0
  return sidBufferToString(koffi.decode(sidPtr, 'uint8', 8 + count * 4) as Uint8Array)
}

/**
 * 当前用户账号名（**域限定**，如 `SUPCON\wangruobiao` 或 `MACHINE\user`）。
 *
 * ⚠ 与 `currentUserSid` 同因：裸 `USERNAME` 在加域机上会被解析到同名本地账号。凡是把用户名交给
 * Win32 解析（`LookupAccountNameW`、codex setup 的 `real_user`）的地方，一律用本函数。
 */
export function currentUserAccountName(): string {
  const domain = process.env.USERDOMAIN
  const name = process.env.USERNAME ?? ''
  return domain && name ? `${domain}\\${name}` : name
}

/**
 * 当前进程用户的 SID（**从进程 token 取**，权威且无重名歧义）。
 *
 * ⚠ 不能按 `USERNAME` 走 `LookupAccountNameW`：加域机上同名本地账号会被优先解析到，
 * 得到的 SID 与真实 token 不同 ⇒ 管道/目录 ACE 永远匹配不上（本仓实测：域账号
 * `supcon\wangruobiao` = S-1-5-21-1718475219-… 被解析成同名本地账号 S-1-5-21-2640670013-…）。
 */
export function currentUserSid(): string {
  const OpenProcessToken = advapi().func('int OpenProcessToken(void* process, uint32 access, void* token)')
  const GetCurrentProcess = kernel32().func('void* GetCurrentProcess()')
  const GetTokenInformation = advapi().func('int GetTokenInformation(void* token, uint32 infoClass, void* info, uint32 len, uint32* needed)')
  const TOKEN_QUERY = 0x0008
  const TokenUser = 1
  const hToken = koffi.alloc('void*', 1)
  if (!OpenProcessToken(GetCurrentProcess(), TOKEN_QUERY, hToken)) {
    throw new Error(`OpenProcessToken failed err=${getLastError()}`)
  }
  const token = koffi.decode(hToken, 'void*')
  const needed = koffi.alloc('uint32', 1)
  // 首次调用取所需长度（预期失败 ERROR_INSUFFICIENT_BUFFER=122）。
  GetTokenInformation(token, TokenUser, null, 0, needed)
  const len = koffi.decode(needed, 'uint32') as number
  if (!len) throw new Error(`GetTokenInformation(TokenUser) 未返回长度 err=${getLastError()}`)
  const buf = koffi.alloc('uint8', len)
  if (!GetTokenInformation(token, TokenUser, buf, len, needed)) {
    throw new Error(`GetTokenInformation(TokenUser) failed err=${getLastError()}`)
  }
  // TOKEN_USER 首字段是 SID_AND_ATTRIBUTES{ PSID Sid; DWORD Attributes } ⇒ 前 8 字节是 SID 指针。
  const sidPtr = koffi.decode(buf, 'void*')
  return sidPointerToString(sidPtr)
}

