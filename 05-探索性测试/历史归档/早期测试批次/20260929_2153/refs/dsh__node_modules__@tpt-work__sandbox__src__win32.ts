/**
 * 提权档的 Win32 FFI 绑定——与 `ffi.ts`（管道 host）分开：
 * 本模块只承载 setup/凭据/提权 spawn 所需的 advapi32/crypt32/kernel32 调用，全部经 koffi。
 *
 * 覆盖：
 *  - DPAPI（crypt32）：`CryptProtectData`/`CryptUnprotectData` —— sandbox_users.json 的密码列。
 *  - SDDL → SECURITY_DESCRIPTOR（advapi32）：给命名管道建「沙箱用户 + 当前用户」双 ACE DACL。
 *  - CreateProcessWithLogonW（advapi32）：非提权父进程以沙箱用户拉起 runner。
 *
 * ⚠ **不含 netapi32**：建/复用本地组与沙箱用户、重置密码都在**已签名的上游 setup exe** 里做
 * （payload 传不进组名与账号策略，我方无法代办），本包从来没有那条绑定；早先文档写它有，是假的。
 * @module
 */

import koffi from 'koffi'
import { lazily, loadWin32Library } from './win32-load.ts'

// ⚠ DLL 装载与函数绑定一律惰性（`xxx()` 先取绑定再调用，memo 化只装载一次）：
// 本包的 `index` 被 `dsh-sandbox-local` 静态 import，而后者是各平台常驻 entry ⇒ 顶层
// `koffi.load('kernel32.dll')` 会让非 Windows 的 backend 连装配都过不去。缘由与语义等价处理见 `win32-load.ts`。
// koffi 的**结构体注册**留在模块顶层：它是纯 JS 侧类型登记、跨平台安全，且必须早于任何引用这些类型名的 `.func()` 原型解析。
const advapi = lazily(() => loadWin32Library('advapi32.dll'))
const crypt32 = lazily(() => loadWin32Library('crypt32.dll'))
const kernel32 = lazily(() => loadWin32Library('kernel32.dll'))

/** CRYPTPROTECT_UI_FORBIDDEN：禁止 DPAPI 弹 UI（服务/无交互上下文必须）。 */
export const CRYPTPROTECT_UI_FORBIDDEN = 0x1

/**
 * 注册 koffi 结构体（**幂等**）。
 *
 * ⚠ 打包态可能同时存在两份本包（`node_modules/@tpt-work/sandbox` 提升一份 +
 * `sandbox-ui/node_modules/@tpt-work/sandbox` 嵌套一份）⇒ koffi 的类型注册是**进程全局**的，
 * 第二份再注册同名类型会抛 `Duplicate type name 'TPT_DATA_BLOB'`（打包自检实撞）。已注册即复用。
 * 因此后续一律用**类型名字符串**（koffi 支持）而不再依赖返回的类型对象。
 * @param name - 全局唯一类型名。
 * @param shape - 字段表。
 */
function registerStruct(name: string, shape: Record<string, string>): void {
  try {
    koffi.struct(name, shape)
  } catch {
    /* 已注册（同一进程里本包被加载了两次）：复用 */
  }
}

registerStruct('TPT_DATA_BLOB', {
  cbData: 'uint32',
  pbData: 'uint8*',
})

const CryptProtectDataFn = lazily(() => crypt32().func(
  'int CryptProtectData(TPT_DATA_BLOB* pDataIn, wchar_t* szDescr, TPT_DATA_BLOB* pEntropy, void* reserved, void* prompt, uint32 flags, TPT_DATA_BLOB* pDataOut)',
))
const CryptUnprotectDataFn = lazily(() => crypt32().func(
  'int CryptUnprotectData(TPT_DATA_BLOB* pDataIn, void* ppszDescr, TPT_DATA_BLOB* pEntropy, void* reserved, void* prompt, uint32 flags, TPT_DATA_BLOB* pDataOut)',
))
const LocalFreeFn = lazily(() => kernel32().func('void* LocalFree(void* h)'))

/** 分配一段字节缓冲并拷入 Node Buffer，返回原生指针。 */
function allocBytes(buf: Buffer): unknown {
  const p = koffi.alloc('uint8', Math.max(1, buf.length))
  // ⚠ 用 `koffi.encode` 而非 `koffi.view`：view 走 **external ArrayBuffer**，Electron 的 utilityProcess
  // 禁止外部缓冲 ⇒ 调用即 `napi_fatal_error` 整进程 abort（exit 134）。encode 是「JS → C memory」正路。
  if (buf.length > 0) koffi.encode(p, 'uint8', buf, buf.length)
  return p
}

/** 分配一个 DATA_BLOB 结构并写入字段，返回其指针（koffi 不自动回写嵌套指针，故显式 decode）。 */
function allocBlob(cbData: number, pbData: unknown): unknown {
  const p = koffi.alloc('TPT_DATA_BLOB', 1)
  koffi.encode(p, 'TPT_DATA_BLOB', { cbData, pbData })
  return p
}

/** 用 DPAPI 当前用户作用域加密一段明文（返回不透明密文 Buffer）。 */
export function dpapiProtect(plain: string): Buffer {
  const input = Buffer.from(plain, 'utf8')
  const inPtr = allocBlob(input.length, allocBytes(input))
  const outPtr = allocBlob(0, null)
  const ok = CryptProtectDataFn()(inPtr, null, null, null, null, CRYPTPROTECT_UI_FORBIDDEN, outPtr)
  if (!ok) throw new Error(`CryptProtectData failed err=${getLastError()}`)
  const out = koffi.decode(outPtr, 'TPT_DATA_BLOB') as { cbData: number; pbData: unknown }
  const buf = Buffer.from(koffi.decode(out.pbData, 'uint8', out.cbData))
  localFree(out.pbData)
  return buf
}

/** 解开 DPAPI 当前用户作用域密文，返回明文（非提权父进程读 setup 产物用）。 */
export function dpapiUnprotect(cipher: Buffer): string {
  const inPtr = allocBlob(cipher.length, allocBytes(cipher))
  const outPtr = allocBlob(0, null)
  const ok = CryptUnprotectDataFn()(inPtr, null, null, null, null, CRYPTPROTECT_UI_FORBIDDEN, outPtr)
  if (!ok) throw new Error(`CryptUnprotectData failed err=${getLastError()}`)
  const out = koffi.decode(outPtr, 'TPT_DATA_BLOB') as { cbData: number; pbData: unknown }
  const text = Buffer.from(koffi.decode(out.pbData, 'uint8', out.cbData)).toString('utf8')
  localFree(out.pbData)
  return text
}

function getLastError(): number {
  return (kernel32().func('uint GetLastError()') as () => number)()
}

/** SDDL → SECURITY_DESCRIPTOR 指针（调用方负责 LocalFree）。 */
export function securityDescriptorFromSddl(sddl: string): unknown {
  const ptr = koffi.alloc('void*', 1)
  const Convert = advapi().func('int ConvertStringSecurityDescriptorToSecurityDescriptorW(wchar_t* s, uint32 rev, void* ppSd, void* size)')
  const ok = Convert(sddl, 1, ptr, null)
  if (!ok) throw new Error(`ConvertStringSecurityDescriptorToSecurityDescriptorW failed err=${kernel32().func('uint GetLastError()')()}`)
  return koffi.decode(ptr, 'void*')
}

export function localFree(ptr: unknown): void {
  if (ptr) LocalFreeFn()(ptr)
}

registerStruct('TPT_SECURITY_ATTRIBUTES', {
  nLength: 'uint32',
  lpSecurityDescriptor: 'void*',
  bInheritHandle: 'int',
})

/**
 * 由 SDDL 构造 SECURITY_ATTRIBUTES（供 CreateNamedPipeW 的 lpSecurityAttributes 用）。
 * 提权路径必须给管道显式 DACL：默认 DACL 只含当前用户，沙箱用户（另一账户）连不上。
 */
export function securityAttributesFromSddl(sddl: string): unknown {
  const sd = securityDescriptorFromSddl(sddl)
  const sa = koffi.alloc('TPT_SECURITY_ATTRIBUTES', 1)
  koffi.encode(sa, 'TPT_SECURITY_ATTRIBUTES', {
    nLength: koffi.sizeof('TPT_SECURITY_ATTRIBUTES'),
    lpSecurityDescriptor: sd,
    bInheritHandle: 0,
  })
  return sa
}

