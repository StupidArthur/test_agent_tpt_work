/**
 * 沙箱一次性 setup 的命令行入口（research/codex-elevated-sandbox-blueprint 的人工提权步骤）+ 真机隔离验证。
 *
 * 用法（管理员/交互会话，会弹 UAC）：
 *   node lib/setup-cli.mjs --workspace <dir> [--sandbox-home <dir>] [--read-root <dir>]... [--write-root <dir>]...
 *   node lib/setup-cli.mjs --workspace <dir> --dry-run    # 只打印 payload/就绪状态，不提权
 *   node lib/setup-cli.mjs --workspace <dir> --verify     # setup 就绪后跑真机隔离断言（不需管理员）
 *
 * `--verify` 断言（经真实装配链：runner → FFI → codex-command-runner，以沙箱用户身份）：
 *   1. read-only 写工作区 → **文件不落盘**（真写隔离）
 *   2. workspace-write 写工作区 → 文件落盘
 *   3. read-only 只读命令 → 输出正确 + exit 0
 * 默认 `--sandbox-home` 与 runner 读取点同一路径（`defaultSandboxHome`）。产物落在 `<codex-home>/`。
 * @module
 */

import { existsSync, mkdirSync, rmSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { ensureRunnerBinaries } from './binaries.ts'
import { currentUserAccountName } from './win32.ts'
import { buildSetupPayload, ensureSandboxSetup, resolveSetupExe, SETUP_VERSION, type SetupRequest } from './setup.ts'
import { sandboxSetupComplete } from './sandbox-users.ts'
import { defaultSandboxHome } from './paths.ts'

function flagValue(args: readonly string[], name: string): string | undefined {
  const i = args.indexOf(name)
  return i >= 0 ? args[i + 1] : undefined
}
function flagValues(args: readonly string[], name: string): string[] {
  const out: string[] = []
  for (let i = 0; i < args.length; i++) if (args[i] === name && args[i + 1] !== undefined) out.push(args[i + 1]!)
  return out
}

/** runner 入口：build 后 lib/runner.mjs 与本文件同目录。 */
function runnerEntryPath(): string {
  return fileURLToPath(new URL('./runner.mjs', import.meta.url))
}

/** 经真实装配链跑一条受限命令（runner → FFI → sandbox runner，提权就绪时以沙箱用户身份）。 */
function runConfined(sandboxHome: string, workspace: string, mode: 'read-only' | 'workspace-write', command: string[]): { code: number; out: string } {
  const res = spawnSync(process.execPath, [runnerEntryPath(), '--workspace', workspace, '--mode', mode, '--', ...command], {
    encoding: 'utf8',
    timeout: 120_000,
    env: { ...process.env, TPT_SANDBOX_HOME: sandboxHome, TPT_SANDBOX_MODE: 'elevated' },
  })
  return { code: res.status ?? -1, out: `${res.stdout ?? ''}${res.stderr ?? ''}` }
}

/** 真机隔离断言（需 setup 已就绪）。 */
function verifyIsolation(sandboxHome: string, workspace: string): number {
  if (!sandboxSetupComplete(sandboxHome)) {
    process.stderr.write(`[verify] setup 未就绪：${sandboxHome}（先以管理员跑一次本 CLI）\n`)
    return 1
  }
  const roFile = join(workspace, 'verify-readonly-should-not-exist.txt')
  const wsFile = join(workspace, 'verify-workspace-write.txt')
  for (const f of [roFile, wsFile]) { try { rmSync(f, { force: true }) } catch { /* 忽略 */ } }

  const results: Array<{ name: string; ok: boolean; detail: string }> = []

  // ⚠ 一律用**相对文件名**（cwd=workspace）：codex 会把 command argv 重组成 cmdline，手写绝对路径的
  // `"..."` 会被追加转义成 `\"...\"` ⇒ cmd 报语法错、写根本没发生、断言假绿（e2e 账本同款坑）。
  const ro = runConfined(sandboxHome, workspace, 'read-only', ['cmd', '/c', 'echo SHOULD-NOT > verify-readonly-should-not-exist.txt'])
  results.push({ name: 'read-only 写工作区被拒', ok: !existsSync(roFile), detail: `exit=${ro.code} fileCreated=${existsSync(roFile)}` })

  const ws = runConfined(sandboxHome, workspace, 'workspace-write', ['cmd', '/c', 'echo OK > verify-workspace-write.txt'])
  results.push({ name: 'workspace-write 写工作区成功', ok: existsSync(wsFile), detail: `exit=${ws.code} fileCreated=${existsSync(wsFile)}` })

  const roRead = runConfined(sandboxHome, workspace, 'read-only', ['cmd', '/c', 'echo VERIFY-READ-OK'])
  results.push({ name: 'read-only 只读命令输出正确', ok: roRead.code === 0 && roRead.out.includes('VERIFY-READ-OK'), detail: `exit=${roRead.code}` })

  // 目标原话「工作区外拒写」：workspace-write 下写**工作区之外**（父目录）必须被拒。
  const outsideFile = join(workspace, '..', 'verify-outside-should-not-exist.txt')
  try { rmSync(outsideFile, { force: true }) } catch { /* 忽略 */ }
  const outside = runConfined(sandboxHome, workspace, 'workspace-write', ['cmd', '/c', 'echo OUT > ..\\verify-outside-should-not-exist.txt'])
  results.push({ name: 'workspace-write 写工作区之外被拒', ok: !existsSync(outsideFile), detail: `exit=${outside.code} fileCreated=${existsSync(outsideFile)}` })
  try { rmSync(outsideFile, { force: true }) } catch { /* 忽略 */ }

  let allOk = true
  for (const r of results) {
    if (!r.ok) allOk = false
    process.stdout.write(`[${r.ok ? 'PASS' : 'FAIL'}] ${r.name} :: ${r.detail}\n`)
  }
  for (const f of [roFile, wsFile]) { try { rmSync(f, { force: true }) } catch { /* 忽略 */ } }
  process.stdout.write(`[verify] ALL_PASS = ${allOk}\n`)
  return allOk ? 0 : 1
}

async function main(): Promise<number> {
  const args = process.argv.slice(2)
  // --sandbox-home 可省：默认与 runner 读取点同一路径（defaultSandboxHome），保证 setup 产物与消费端对齐。
  const sandboxHome = flagValue(args, '--sandbox-home') ?? defaultSandboxHome()
  const workspace = flagValue(args, '--workspace')
  if (!workspace) {
    process.stderr.write('usage: setup-cli --workspace <dir> [--sandbox-home <dir>] [--read-root <dir>]... [--write-root <dir>]... [--dry-run|--verify]\n')
    return 2
  }
  const readRoots = flagValues(args, '--read-root')
  const writeRoots = flagValues(args, '--write-root')
  const request: SetupRequest = {
    sandboxHome,
    commandCwd: workspace,
    readRoots: readRoots.length > 0 ? readRoots : [workspace],
    writeRoots: writeRoots.length > 0 ? writeRoots : [workspace],
    realUser: currentUserAccountName(),
  }

  if (args.includes('--verify')) return verifyIsolation(sandboxHome, workspace)

  const setupExe = resolveSetupExe()
  process.stdout.write(`[tpt-sandbox setup] setup exe: ${setupExe ?? '(未找到——先跑 postinstall bootstrap 下载)'}\n`)
  process.stdout.write(`[tpt-sandbox setup] SETUP_VERSION=${SETUP_VERSION} 已就绪=${sandboxSetupComplete(sandboxHome)}\n`)

  if (args.includes('--dry-run')) {
    process.stdout.write(`[tpt-sandbox setup] payload(dry-run)=\n${JSON.stringify(buildSetupPayload(request), null, 2)}\n`)
    return 0
  }
  // 二进制缺失时先补齐（打包态首次运行无需 postinstall）。
  if (setupExe === undefined) {
    process.stdout.write('[tpt-sandbox setup] setup exe 缺失，尝试下载…\n')
    const { runner, setup } = await ensureRunnerBinaries()
    if (!setup) {
      process.stderr.write('[tpt-sandbox setup] 下载 setup exe 失败（检查内网镜像/网络）\n')
      return 1
    }
    process.stdout.write(`[tpt-sandbox setup] 二进制就位：runner=${runner} setup=${setup}\n`)
  }
  // 默认 codex-home 可能尚不存在 ⇒ 建出来（setup 的 prepare_setup_marker 也需要父目录可写）。
  mkdirSync(sandboxHome, { recursive: true })
  const ran = await ensureSandboxSetup(request)
  process.stdout.write(`[tpt-sandbox setup] ${ran ? '本次已执行提权 setup' : '原本已就绪，跳过'}\n`)
  process.stdout.write(`[tpt-sandbox setup] 就绪=${sandboxSetupComplete(sandboxHome)}\n`)
  return sandboxSetupComplete(sandboxHome) ? 0 : 1
}

process.exit(await main())
