/**
 * 沙箱两个官方二进制的**运行时**获取（打包态首次运行用；postinstall 的
 * `scripts/bootstrap.mjs` 是同一 lock 的 install 期消费方）。
 *
 * **唯一声明位** = `sandbox-binary-lock.json`：release pin / 资产名 / 落盘名 / 字节数 /
 * 体量下限 / 源基址只在那一份 JSON 里，本模块只消费不复制（门禁钉同源 =
 * `tests/quality/sandbox-binary-lock-single-source.spec.ts`，账本
 * `implementation/imp-adopt-upstream-copy-batch` 章节 B）。URL 拼接 =
 * `{base}/{assetPath}/{release}/{asset}`（nexus 镜像映射完整 GitHub 路径，少一段即 404）。
 *
 * 落盘判据 = 按 lock 复算 sha256（照上游 `downloadPrimaryRuntimeAsset` 的形状搬到运行期）：
 * 写 `*.tmp`（唯一命名）→ 流式复算（体量预检先行省 IO）→ `rename` 原子落位；一切抛错
 * 分支清半写 tmp、绝不触碰在位文件。复算不匹配即删 tmp 换下一源，全源败尽返回 false
 * （调用方 fail-closed 口径不变）。重定向只手工跟 ≤5 跳，且跳转目标必须 https 或与
 * 首发同源——拦 https→http 降级与任意异站跳转；镜像通道本身走 http 是既有拍板，摘要
 * 兜底不依赖 https。
 *
 * ⚠ 相对旧口径的两处行为变化（章节 B）：
 * ① 在位判定从「MZ+体量」升为「按 lock 复算」——被换的在位件与升 pin 后的旧件都会在
 *    启动补拉时被替换（pin 提升自动生效）；
 * ② 抛错分支清半写 tmp（tmp 唯一命名 ⇒ postinstall 与启动补拉并发写同一安装位不互踩，
 *    先到先落、后到等值覆盖）。`dest` 被运行中进程占用时 rename 抛 EPERM/EBUSY ⇒ 清 tmp、
 *    dest 原样、返回 false，候选链旧件仍按 MZ+体量可用。
 *
 * 本模块同时是二进制有效性的唯一判定处：`isValidBinary`（MZ+minSize）与 `pickValidBinary`
 * 被候选解析方（`paths.ts` / `setup.ts`）复用——候选解析环节保留 MZ+体量卫生门（身份判定
 * 收在写入时刻，runner 每次 spawn 复算 23.6 MB 的成本口径不划算），兜底候选不得落到同用户
 * 可写目录（`%TEMP%`/`cwd/temp`）。
 *
 * ⚠ `paths.ts` 与本模块存在双向 import：本模块只在**函数体**内用 `runnerInstallDir`，
 * `paths.ts` 只在函数体内用本模块的判定函数，两侧顶层都是纯字面量/函数声明 ⇒ 任意求值顺序
 * 都无 TDZ（ESM 函数声明在实例化期可用；顶层 `entryOf` 只消费静态 import 的 lock）。
 * 新增顶层消费前必须重审这一约束。
 * @module
 */

import { createHash, randomBytes } from 'node:crypto'
import { createWriteStream, existsSync, mkdirSync, openSync, readSync, closeSync, renameSync, rmSync, statSync } from 'node:fs'
import { get as httpGet } from 'node:http'
import { get as httpsGet } from 'node:https'
import { join } from 'node:path'
import { runnerInstallDir } from './paths.ts'
import lock from './sandbox-binary-lock.json' with { type: 'json' }

/** lock 单条的消费形状：`file` = release 资产名，`dest` = 落盘名，`bytes` = pin 版字节数（体量预检），`minSize` = 候选卫生门的体量下限，`sha256` = 落盘判据。 */
export interface SandboxBinaryEntry {
  readonly file: string
  readonly dest: string
  readonly bytes: number
  readonly minSize: number
  readonly sha256: string
}

/** 沙箱二进制的 pin 版 release tag——唯一声明位是 lock 的 `release`，此处只是派生读数。 */
export const SANDBOX_BINARY_RELEASE: string = lock.release

/** 取 lock.files 第 `index` 颗并定格为消费形状；缺席即抛（lock 形状变了 ⇒ 消费方必须跟着改，不留静默半值）。 */
function entryOf(index: number): SandboxBinaryEntry {
  const entry = lock.files[index]
  if (entry === undefined) throw new Error(`sandbox-binary-lock.json: files[${String(index)}] 缺席，消费方按章节 B 口径适配`)
  return { file: entry.asset, dest: entry.dest, bytes: entry.bytes, minSize: entry.minBytes, sha256: entry.sha256 }
}

/** 需要随包/运行期就位的两个二进制（lock.files 序：0 = runner、1 = setup；这个次序被 `ensureRunnerBinaries` 的下标消费，由根 quality 门禁钉住）。 */
export const SANDBOX_BINARIES: readonly [SandboxBinaryEntry, SandboxBinaryEntry] = [entryOf(0), entryOf(1)]

/** sandbox-runner.exe 的最小可信体量（候选校验门槛；声明位在 lock 的 `minBytes`）。 */
export const RUNNER_EXE_MIN_SIZE: number = SANDBOX_BINARIES[0].minSize
/** sandbox-setup.exe 的最小可信体量（同上）。 */
export const SETUP_EXE_MIN_SIZE: number = SANDBOX_BINARIES[1].minSize
/** codex windows 沙箱 setup 二进制的 release 资产落盘名（原定义在 setup.ts，上移到此消除循环 import）。 */
export const SETUP_EXE_FILENAME: string = SANDBOX_BINARIES[1].dest

/** 镜像基址覆盖的 env 缝名——与 lock 里 kind=mirror 那颗的 `env` 同名（根 quality 门禁钉两侧同名）。 */
const MIRROR_BASE_ENV = 'TPT_SANDBOX_MIRROR_BASE'

/** 是否有效 PE（MZ 魔数）且量级达标（候选解析链的卫生门；身份判定在写入时刻按 lock 复算，见 `matchesLock`）。 */
export function isValidBinary(file: string, minSize: number): boolean {
  try {
    if (!existsSync(file)) return false
    if (statSync(file).size < minSize) return false
    const fd = openSync(file, 'r')
    try {
      const buf = Buffer.alloc(2)
      readSync(fd, buf, 0, 2, 0)
      return buf[0] === 0x4d && buf[1] === 0x5a
    } finally {
      closeSync(fd)
    }
  } catch {
    return false
  }
}

/**
 * 依序取第一个**有效**（MZ + minSize）候选；全无效返回 undefined。
 * 候选解析（`resolveRunnerExe` / `resolveSetupExe`）统一经此门——只 existsSync 的候选会把
 * 同用户可写目录里被投放的同名文件拉起成提权（UAC）/执法（沙箱用户）执行体。
 */
export function pickValidBinary(candidates: readonly string[], minSize: number): string | undefined {
  for (const candidate of candidates) {
    if (isValidBinary(candidate, minSize)) return candidate
  }
  return undefined
}


/** lock.sources 派生的源基址清单（优先序不变）；镜像 env 缝在位则整体替换 mirror 那颗。 */
function basesFromLock(): readonly string[] {
  const override = process.env[MIRROR_BASE_ENV]
  return lock.sources.map((source) => (source.kind === 'mirror' && override !== undefined && override !== '' ? override : source.base))
}

/** 全文件 sha256（流式分块读，23.6 MB 不整体入内存）；读不了 ⇒ undefined（调用方按不匹配处理）。 */
export function sha256OfFile(file: string): string | undefined {
  try {
    const hash = createHash('sha256')
    const fd = openSync(file, 'r')
    try {
      const buf = Buffer.alloc(1 << 20)
      for (;;) {
        const read = readSync(fd, buf, 0, buf.length, null)
        if (read === 0) break
        hash.update(buf.subarray(0, read))
      }
    } finally {
      closeSync(fd)
    }
    return hash.digest('hex')
  } catch {
    return undefined
  }
}

/**
 * lock 的落盘判据：先比 `bytes` 体量预检（不等即判不匹配，省一次全读），再全文件 sha256
 * 全等。在位判定与下载后判定用同一把尺。
 * @param file - 待验文件路径。
 * @param entry - 提供 `bytes`/`sha256` 的 lock 条目（测试注入同形状夹具）。
 */
export function matchesLock(file: string, entry: { bytes: number; sha256: string }): boolean {
  try {
    if (statSync(file).size !== entry.bytes) return false
  } catch {
    return false
  }
  return sha256OfFile(file) === entry.sha256
}

/** 手工跟跳上限（不用 fetch 自动跟跳：每一跳的目标协议与 host 必须逐跳判）。 */
const MAX_REDIRECTS = 5

/**
 * 单次下载流式写 `tmp`（绝不直接写 dest）。
 * 重定向口径：3xx 手工跟 ≤`hopsLeft` 跳；目标为 http: 时必须与首发 URL 同 host——拦
 * https→http 降级与任意异站跳转（镜像通道本身的 http 首发不受此限，是既有拍板通道）。
 */
function download(url: string, tmp: string, hopsLeft: number, originHost: string): Promise<void> {
  const request = url.startsWith('https:') ? httpsGet : httpGet
  return new Promise((resolve, reject) => {
    const req = request(url, { timeout: 120_000 }, (res) => {
      if (res.statusCode !== undefined && res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        res.resume()
        req.destroy()
        if (hopsLeft <= 0) {
          reject(new Error(`redirect limit (${String(MAX_REDIRECTS)} hops) exceeded at ${url}`))
          return
        }
        let next: URL
        try {
          next = new URL(res.headers.location, url)
        } catch {
          reject(new Error(`invalid redirect target ${String(res.headers.location)} at ${url}`))
          return
        }
        if (next.protocol === 'http:' && next.host !== originHost) {
          reject(new Error(`redirect off-list (http redirect to foreign host): ${url} -> ${next.href}`))
          return
        }
        download(next.href, tmp, hopsLeft - 1, originHost).then(resolve, reject)
        return
      }
      if (res.statusCode !== 200) {
        res.resume()
        reject(new Error(`download ${url} -> HTTP ${String(res.statusCode)}`))
        return
      }
      const out = createWriteStream(tmp)
      res.pipe(out)
      out.on('finish', () => out.end(() => resolve()))
      res.on('error', reject)
      out.on('error', reject)
    })
    req.on('error', reject)
    req.on('timeout', () => req.destroy(new Error('download timeout')))
  })
}

/** 体量读数（读不了 ⇒ -1，只服务于失败诊断文案）。 */
function sizeOf(file: string): number {
  try {
    return statSync(file).size
  } catch {
    return -1
  }
}

/**
 * 确保一个二进制在落点就位且**与 lock 摘要一致**（幂等）。
 * 下载链 = `*.tmp` 唯一命名写入 → 按 lock 复算 sha256 → `rename` 原子落位；一切抛错分支
 * （传输失败/超时/跳数超限/摘要不匹配/rename 被占用）删半写 tmp，在位 dest 不动。
 * @param entry - lock 派生条目（测试注入同形状夹具）。
 * @param options.bases - 覆写源基址清单（测试指进程内假源）；默认 = lock.sources + 镜像 env 缝。
 * @param options.destDir - 覆写落点（测试注入 `mkdtemp` 隔离目录，R8）；默认 = 安装位。
 * @returns `true` = 已在位或下载并复算成功；`false` = 全源失败（调用方自行 fail-closed）。
 */
export async function ensureBinary(
  entry: SandboxBinaryEntry,
  options: { readonly bases?: readonly string[]; readonly destDir?: string } = {},
): Promise<boolean> {
  const dir = options.destDir ?? runnerInstallDir()
  const dest = join(dir, entry.dest)
  if (matchesLock(dest, entry)) return true
  mkdirSync(dir, { recursive: true })
  const bases = options.bases ?? basesFromLock()
  const tmp = join(dir, `${entry.dest}.tmp-${String(process.pid)}-${randomBytes(4).toString('hex')}`)
  for (const base of bases) {
    const url = `${base.replace(/\/+$/u, '')}/${lock.assetPath}/${lock.release}/${entry.file}`
    let originHost: string
    try {
      originHost = new URL(url).host
    } catch {
      console.warn(`[tpt-sandbox] ${entry.dest}: base is not a valid URL, skipping: ${base}`)
      continue
    }
    try {
      await download(url, tmp, MAX_REDIRECTS, originHost)
      if (!matchesLock(tmp, entry)) {
        throw new Error(`sha256 mismatch for ${entry.dest} (expected ${entry.sha256}, actual ${sha256OfFile(tmp) ?? 'unreadable'} / ${String(sizeOf(tmp))} bytes)`)
      }
      renameSync(tmp, dest)
      return true
    } catch (error) {
      // 一切抛错分支都清半写件（J2：安装位不残留 *.tmp、dest 字节不变），带期望/实际摘要
      // 的对账读数打出来，再换下一源。
      rmSync(tmp, { force: true })
      console.warn(`[tpt-sandbox] download failed from ${url}: ${error instanceof Error ? error.message : String(error)}`)
    }
  }
  return false
}

/** 确保 runner + setup 两个二进制都就位（打包态首次运行调用）。
 *  ⚠ 这两个是 Windows 专属 PE 可执行（codex-command-runner / codex-windows-sandbox-setup）。
 *  只在 win32 上下载/校验；macOS 等平台用 dsh 自带的原生沙箱（自己的插件），这里免下载、免占坑。 */
export async function ensureRunnerBinaries(): Promise<{ runner: boolean; setup: boolean }> {
  if (process.platform !== 'win32') {
    return { runner: false, setup: false }
  }
  const [runner, setup] = await Promise.all([ensureBinary(SANDBOX_BINARIES[0]), ensureBinary(SANDBOX_BINARIES[1])])
  return { runner, setup }
}
