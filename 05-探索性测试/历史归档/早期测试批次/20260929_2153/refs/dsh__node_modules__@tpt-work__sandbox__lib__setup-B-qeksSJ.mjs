import { D as shellExecuteRunas, a as sandboxSetupComplete, b as pickValidBinary, g as SETUP_EXE_MIN_SIZE, h as SETUP_EXE_FILENAME, n as ONLINE_USERNAME, t as OFFLINE_USERNAME, y as isValidBinary } from "./sandbox-users-RF79M0K_.mjs";
import { homedir } from "node:os";
import { join } from "node:path";
import { TPT_HOME_DIR_NAME } from "@tpt-work/data-root";
import { spawnSync } from "node:child_process";
//#region src/setup.ts
/**
* 沙箱一次性 setup（research/codex-elevated-sandbox-blueprint 提权路径）。
*
* **不自建沙箱用户**：改用 codex 官方 `sandbox-setup.exe`（release 资产，与 runner 同版本），
* 它吃一个 base64(JSON payload) 参数，产出 `<codex_home>/.sandbox/setup_marker.json` 与
* `<codex_home>/.sandbox-secrets/sandbox_users.json`（DPAPI 密码），并配置沙箱用户/组与 ACL。
* TPT 只负责：构造 payload → 以 `runas`(UAC) 拉起它 → 读产物。
*
* payload 逐字段对齐 codex `windows-sandbox-rs/src/bin/setup_main/win.rs` 的 `Payload`（SETUP_VERSION=5），
* 已用真二进制实测：非提权下报 `helper_users_group_create_failed … code 5`（=schema 正确、仅缺提权）。
* @module
*/
/** codex `setup.rs` 的 `SETUP_VERSION`（版本不符会被 setup 拒绝）。 */
const SETUP_VERSION = 5;
/**
* `real_user` 必须是域/机器限定的账号名，就地 fail-closed。
*
* 这不是格式洁癖：裸 `USERNAME` 在加域机上会被 `LookupAccountNameW` 解析到**同名本地账号**（本仓
* 在 `currentUserSid`/`currentUserAccountName` 两处各踩过一次并各留了一条注释）。后果不是报错，
* 而是 **ACE 授错人**：setup 退出码 0、两个沙箱账号照建，但读权限给了那个本地同名账号 ⇒ 真实用户
* 连自己数据根里的 `setup_marker.json` 都读不到 ⇒ `sandboxSetupComplete` 永远 false，提权档
* 表现为「装了、跑过 setup、却永远没就绪」，且现场没有任何一条错误信息指向真正的原因。
* 本机实测：payload 给 `wangruobiao` ⇒ 目录 DACL 长出 `WANGRUOBIAO\` 这条 trustee；给
* `SUPCON\wangruobiao` ⇒ `SUPCON\wangruobiao`（正确）。
*/
function assertQualifiedAccountName(name) {
	if (!name.includes("\\")) throw new Error(`real_user 必须是域/机器限定的账号名（收到 "${name}"，形如 DOMAIN\\user）：裸名在加域机上会被解析到同名本地账号，ACE 会授错人`);
}
/** 构造 codex setup 的 payload（字段名/取值与 codex 侧逐字一致）。 */
function buildSetupPayload(request) {
	assertQualifiedAccountName(request.realUser);
	return {
		version: 5,
		offline_username: OFFLINE_USERNAME,
		online_username: ONLINE_USERNAME,
		codex_home: request.sandboxHome,
		command_cwd: request.commandCwd,
		read_roots: request.readRoots,
		write_roots: request.writeRoots,
		deny_read_paths: [],
		deny_write_paths: [],
		proxy_ports: [],
		allow_local_binding: false,
		real_user: request.realUser,
		mode: "full",
		refresh_only: false
	};
}
/**
* 定位 codex setup 二进制：`TPT_SANDBOX_SETUP` 环境变量 → 安装位。
*
* ⚠ 候选加固（2026-09-13 评审 medium）：删除 `%TEMP%` 与 `process.cwd()/temp` 两个开发探针候选
* ——它们是同用户可写目录，预置/替换同名文件即可让 UAC 提权执行任意 PE。产品态候选收敛为
* 安装位；显式环境变量保留（操作者自担责任的 dev 出口），且**指向无效二进制时直接 undefined**
* （fail-closed，不静默回退安装位）。所有命中统一过 `isValidBinary`（MZ + 最小体量）再使用。
*/
function resolveSetupExe() {
	const fromEnv = process.env.TPT_SANDBOX_SETUP;
	if (fromEnv !== void 0 && fromEnv !== "") return isValidBinary(fromEnv, SETUP_EXE_MIN_SIZE) ? fromEnv : void 0;
	return pickValidBinary([join(setupInstallDir(), SETUP_EXE_FILENAME)], SETUP_EXE_MIN_SIZE);
}
/** setup 二进制的安装位（bootstrap 下载落点）。 */
function setupInstallDir() {
	return join(homedir(), TPT_HOME_DIR_NAME, "sandbox");
}
/**
* 以 UAC 提权运行 codex setup（一次性）。
* ⚠ 非阻塞：`shellExecuteRunas` 的两段等待分支（UAC 应答 + 提权进程执行）在线程池完成，
* 调用方（Remote `installSandbox`）await 即可，backend 事件循环不冻结。
* @returns 提权进程退出码（0 = 成功）。
* @throws setup 二进制缺失、或用户取消 UAC。
*/
async function runElevatedSetup(request) {
	const exe = resolveSetupExe();
	if (!exe) throw new Error(`未找到 ${SETUP_EXE_FILENAME}（应先由 bootstrap 下载到 ${setupInstallDir()}）`);
	const payloadB64 = Buffer.from(JSON.stringify(buildSetupPayload(request)), "utf8").toString("base64");
	return shellExecuteRunas(exe, payloadB64, request.sandboxHome);
}
/**
* 幂等入口：产物已就绪则跳过；否则提权跑一次 setup，返回是否在本次新做。
*
* ⚠ 已就绪时**不再跑 refresh**：refresh 是「按工作区补写 ACE」的活，由 `AclWriteGrant.add` 负责；
* 实测单次约 28s 且是同步 spawn，放进「安装」按钮会让 UI 长时间卡在等待态。
* ⚠ 非阻塞：UAC 等待在线程池，本函数返回 Promise；wire 接口（Remote 方法）支持 Promise 返回
* （调用方 `tptSandbox.installSandbox` 就是 async Remote 方法）。
* @returns `true` = 本次执行了提权 full setup；`false` = 原本已就绪。
*/
async function ensureSandboxSetup(request) {
	if (sandboxSetupComplete(request.sandboxHome)) return false;
	const code = await runElevatedSetup(request);
	if (code !== 0) throw new Error(`沙箱 setup 提权进程退出码 ${code}`);
	if (!sandboxSetupComplete(request.sandboxHome)) throw new Error("沙箱 setup 结束但产物未就绪（sandbox_users.json/setup_marker.json 缺失或版本不符）");
	return true;
}
/**
* 非提权 refresh：按当前 `write_roots` 补授工作区写 ACE + cap SID（codex `run_setup_refresh` 同款）。
* 不触发 UAC；产物缺失/版本不符时 setup 自身会拒绝。
* @returns setup 进程退出码（0 = 成功）。
*/
function runSetupRefresh(request) {
	const exe = resolveSetupExe();
	if (!exe) throw new Error(`未找到 ${SETUP_EXE_FILENAME}（应先由 bootstrap 下载到 ${setupInstallDir()}）`);
	const payload = {
		...buildSetupPayload(request),
		refresh_only: true
	};
	const payloadB64 = Buffer.from(JSON.stringify(payload), "utf8").toString("base64");
	return spawnSync(exe, [payloadB64], {
		windowsHide: true,
		stdio: "ignore",
		timeout: 12e4
	}).status ?? -1;
}
//#endregion
export { runElevatedSetup as a, resolveSetupExe as i, buildSetupPayload as n, runSetupRefresh as o, ensureSandboxSetup as r, setupInstallDir as s, SETUP_VERSION as t };
