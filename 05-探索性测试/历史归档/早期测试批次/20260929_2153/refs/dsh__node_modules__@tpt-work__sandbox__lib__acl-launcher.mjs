import koffi from "koffi";
import { pathToFileURL } from "node:url";
//#region src/acl-launcher.ts
/**
* ACL 档的**控制台垫片**：在**未受限**时给 ACL runner 自己分配一个隐藏控制台，再让上游 runner
* 在本进程里跑起来（argv 逐字透传）。
*
* 为什么需要它（成因不是推理，是社区两条实测 + 我方复现同形）：
*  - 受限子进程的**直系父进程**是 ACL runner。桌面形态下 `process.execPath` 是 Electron（**GUI 子系统**），
*    它永远没有控制台 ⇒ 控制台子系统的子进程（pwsh / cmd / node / python）只能**新分配一个 conhost**；
*    而这次分配用的是**已经受限的令牌**，在受影响机型上于入口之前就死于 `STATUS_DLL_INIT_FAILED`
*    （`0xC0000142`，无输出、无 `windows-acl-run:` 签名 ⇒ 工具层只看到一个裸退出码）。
*  - 对照组读数（同一 runner、同一目标、只换宿主）：真 `node.exe`（**控制台子系统**）⇒ 绿；
*    Electron（带 `ELECTRON_RUN_AS_NODE=1`）⇒ `0xC0000142` —— 差别就是"runner 有没有控制台"。
*  - 上游明确**不能**给受限子进程加 `CREATE_NO_WINDOW`/`CREATE_NEW_CONSOLE`（同样死于该码）；
*    正确做法是让子进程**继承**一个已存在的控制台。已落地的同类修法见
*    anywhere-labs/dsh-desktop@a1caef3（在 Node 模式 trampoline 里 `AllocConsole` + `SW_HIDE` 后再 import runner）。
*
* 语义不变（本垫片唯一的职责就是上面那一件事）：
*  - DACL / 限制 SID 表 / 创建旗标 / 上游各条失败路径**一字不动**；
*  - argv 逐字透传：`[execPath, 本文件, runner, ...上游参数]` ⇒ 本进程内重写成
*    `[execPath, runner, ...上游参数]` 后 import 上游 runner，`process.argv.slice(2)` 与直跑时同形；
*  - 控制台分配失败 ⇒ **fail-open**（打一行 stderr 后照原样继续）：那时行为与没有本垫片完全一致，
*    不会把"控制台不可用"升级成"沙箱不可用"。
*
* 撤除条件：宿主或 runner 改用真 `node.exe` 托管（社区 #8193 的实测方向）后，本文件整颗删，
* `entry.ts` 的 ACL 分支回退成 `[process.execPath, 上游 runner]`。
* @module @tpt-work/sandbox/acl-launcher
*/
/** 已有的控制台窗口句柄（`GetConsoleWindow`）；没有控制台时为 0。 */
function existingConsoleWindow() {
	return koffi.load("kernel32.dll").func("void* GetConsoleWindow()")();
}
/**
* 给本进程分配一个隐藏控制台（幂等：已经有控制台就直接返回）。
*
* `AllocConsole` 只在**本进程尚无控制台**时有效；分配出来的窗口用 `SW_HIDE`（0）藏掉，
* 免得每次命令弹一个黑窗。失败返回 false（调用方 fail-open）。
* @returns 是否确认拿到了控制台窗口句柄。
*/
function allocateHiddenConsole() {
	if (existingConsoleWindow() !== null) return true;
	const kernel32 = koffi.load("kernel32.dll");
	const user32 = koffi.load("user32.dll");
	const allocConsole = kernel32.func("int AllocConsole()");
	const getConsoleWindow = kernel32.func("void* GetConsoleWindow()");
	const showWindow = user32.func("int ShowWindow(void* hWnd, int nCmdShow)");
	allocConsole();
	const window = getConsoleWindow();
	if (window === null) return false;
	showWindow(window, 0);
	return true;
}
/** 上游 runner 的入口路径（argv[1]）与其后的原样参数。 */
const [runnerEntry, ...runnerArgs] = process.argv.slice(2);
if (runnerEntry === void 0) {
	process.stderr.write("windows-acl-run: acl-launcher needs the runner entry as its first argument\n");
	process.exitCode = 127;
} else {
	if (process.platform === "win32") try {
		if (!allocateHiddenConsole()) process.stderr.write("[tpt-sandbox] acl-launcher: 控制台分配失败，按原样继续（受限子进程可能需要新建 conhost）\n");
	} catch (error) {
		process.stderr.write(`[tpt-sandbox] acl-launcher: 控制台分配出错，按原样继续：${error instanceof Error ? error.message : String(error)}\n`);
	}
	process.argv = [
		process.argv[0] ?? "node",
		runnerEntry,
		...runnerArgs
	];
	await import(pathToFileURL(runnerEntry).href);
}
//#endregion
export {};
