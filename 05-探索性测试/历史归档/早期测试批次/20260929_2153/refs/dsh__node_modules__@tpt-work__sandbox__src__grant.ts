/**
 * 服务端写授权（implementation/sandbox-decodex-rename-acl-elevated-modes W4 起是**按档分派**的门面）。
 *
 * seam（`dsh-sandbox-local`）只认一个名字：`AclWriteGrant.create(writeSid)`。两档对「谁能写这个
 * 目录」的回答根本不同，所以这里分派：
 *
 *  - `acl`（默认）⇒ **上游 `AclWriteGrant`** 原样上场：给 WRITE_RESTRICTED token 的能力 SID
 *    （`S-1-4-…`）在目录 DACL 上落 ACE。写权限来自「限制 SID 与 DACL 的交集」，真实用户本身
 *    并没有多得到任何写权限。
 *  - `elevated` ⇒ 本文件的 `SandboxUserWriteGrant`：受限命令跑在**另一个低权用户**的 token 上，
 *    所以「只能写这里」必须由该用户（或其组）在 DACL 上真的可写来承载。授出口**只有**上游 setup 的
 *    非提权 refresh 一条（ACE 授给上游派生的 cap SID，icacls 对裸 SID 报 1332）；setup 未就绪即
 *    拒授（`add()` 第一句 fail-closed），不再有「先给真实机器组落一份 ACE、执行侧再拒」的回落
 *    （implementation/imp-adopt-upstream-adapt-batch A-05：命令没跑权限已授 = 白授一份，
 *    且那份 ACE 落在真实存在的 `<hostname>\CodexSandboxUsers` 上，对越权者有价值）。
 *
 * 语义对齐：两档都满足 seam 的契约——`add()` 失败即抛（调用方 dispose 撤销已授的），抛之前**不记**
 * 该 path（撤一条从未授过的 ACE 是假的撤销）。常驻工作区 ACE 两档都不回收（跨会话复用缓存）：
 * `acl` 档由上游 `AclWriteGrant` 自己处置，`elevated` 档见 {@link SandboxUserWriteGrant.dispose}。
 * @module @tpt-work/sandbox/grant
 */

import { hostname } from 'node:os'
import { currentUserAccountName } from './win32.ts'
import { defaultSandboxHome } from './paths.ts'
import { runSetupRefresh } from './setup.ts'
import { sandboxSetupComplete } from './sandbox-users.ts'
import { sandboxMode } from './mode.ts'
import { upstreamAcl, type UpstreamWriteGrant } from './upstream-acl.ts'

/** 默认沙箱账号：本机 CodexSandboxUsers 组（组名由上游二进制硬编码，payload 传不进改名，research/sandbox-decodex-rename-and-acl-elevated-modes §2.3）。 */
export function defaultSandboxGroup(): string {
  return `${hostname()}\\CodexSandboxUsers`
}

/**
 * 一个写 SID 的服务生命周期授权：每条 `add(path)` 经 codex setup 的非提权 refresh 让沙箱用户在
 * 该目录可写，并记录该 path 供 `paths` 读数。与 windows-acl 同 fail-closed：`add` 失败即抛，
 * 调用方 dispose 撤销已授的（本档无物可撤，见 {@link dispose}）。
 */
export class SandboxUserWriteGrant {
  /** 调用方传入的写能力 SID（cap_sids 依据）。 */
  readonly writeSid: string
  /** 本授权绑定的沙箱账号（诊断读数用；授出口已不直接按名授 ACE，故不再参与任何 icacls 串）。 */
  readonly sandboxAccount: string
  private readonly standingPaths: string[] = []
  private readonly revocablePaths: string[] = []

  private constructor(writeSid: string, sandboxAccount: string) {
    this.writeSid = writeSid
    this.sandboxAccount = sandboxAccount
  }

  /**
   * 就绪一个授权（尚无 ACE）。与上游签名对齐：第二个参数兼容旧测试/调用方传的绑定表
   * （字符串之外的值忽略——授出口交给 codex setup，本件不直接做 Win32 ACL 调用）。
   * @param writeSid - 工作区（`S-1-4-x-y`）或 temp（`S-1-4-x-y-1`）能力 SID 字符串。
   * @param sandboxAccount - 可选沙箱账号覆盖（默认 `MachineName\CodexSandboxUsers`），只作诊断读数。
   */
  static create(writeSid: string, sandboxAccount?: string): SandboxUserWriteGrant {
    return new SandboxUserWriteGrant(writeSid, sandboxAccount ?? defaultSandboxGroup())
  }

  /**
   * 给提权档授目录写。**唯一**授出口 = codex setup 的非提权 refresh（幂等：已存在同 ACE 时合并）。
   *
   * 第一句是就绪门：提权档的写权限由真实用户/组承载，上游那条「先落 ACE 后 spawn」在它是无害的
   * （授给 WRITE_RESTRICTED token 的能力 SID，真实用户从中得不到写权限），在这里不成立 ⇒ 只能在
   * 授出口先关门。未就绪即抛，**且此刻尚未记任何 path**（seam 的处置是「`add` 抛 ⇒ `dispose` 撤销
   * 已授的」，记了就会去撤一条从未存在的 ACE）。文案与 `runner.ts` 的拒跑指路句同口径。
   * @param path - 目录绝对路径。
   * @param standing - 语义保留给 seam 契约：常驻工作区能力（dispose 不撤销）。两档都不回收，本参数
   *   只影响 {@link paths} 的记账次序。默认 false（temp 生命周期）。
   */
  add(path: string, standing = false): void {
    const sandboxHome = defaultSandboxHome()
    if (!sandboxSetupComplete(sandboxHome)) {
      throw new Error(
        `tpt-sandbox: 提权档需要一次性 setup，但 ${sandboxHome} 下产物未就绪；拒绝授予写权限。\n`
        + '   -> 设置 · 沙箱 里点「安装沙箱」（一次 UAC 授权），或把档位切回默认的 ACL 档。')
    }
    // 提权模型：写隔离靠受限 token 的 restricting SID 交集，ACE 必须授给**工作区能力 SID**
    // （`S-1-5-21-…`），而 icacls 对裸 SID 报 1332 ⇒ 交给 codex setup 的**非提权 refresh**
    // 施加（`refresh_only: true`，按 write_roots 授 ACE + cap SID）。
    const code = runSetupRefresh({
      sandboxHome,
      commandCwd: path,
      readRoots: [path],
      writeRoots: [path],
      realUser: currentUserAccount(),
    })
    if (code !== 0) {
      throw new Error(`codex setup refresh 授权失败（exit ${code}）：${path}——拒绝以未授权工作区继续`)
    }
    // 授成功才记账（拒授不先记 path：失败不留记账）。
    ;(standing ? this.standingPaths : this.revocablePaths).push(path)
  }

  /** 每条被本授权持有的目录，按授权顺序。 */
  get paths(): readonly string[] {
    return [...this.standingPaths, ...this.revocablePaths]
  }

  /**
   * 无操作：提权档在本件里**从未**授过可回收的组 ACE（`add()` 只经 codex setup refresh 把 ACE
   * 授给 cap SID），所以这里没有任何可撤销的东西——留着 icacls `/remove:g` 就是留着一条对着从未
   * 授过的主体的 DACL 做写、并在 not-found 时把 dispose 变成抛错的路。
   *
   * 提权档的 temp 回收由调用方删目录完成（目录没了 ACE 自然消失）；常驻工作区 ACE 跨会话保留、
   * 不回收（口径登记见 implementation/sandbox-decodex-rename-acl-elevated-modes）。
   */
  dispose(): void {}
}

/** 当前真实用户的账号（域限定，避免加域机上同名本地账号歧义）。 */
export function currentUserAccount(): string {
  return currentUserAccountName()
}

/** 两档授权实例共同满足的 seam 契约（seam 只用这几个成员）。 */
export interface WriteGrant {
  /** SDDL 形式的写能力 SID。 */
  readonly writeSid: string
  /** 给一个目录授写；`standing` = 常驻 ACE，dispose 不撤销。 */
  add(path: string, standing?: boolean): void
  /** 当前带该授权的目录，按授权顺序。 */
  readonly paths: readonly string[]
  /** 撤销本实例可回收的授权：`acl` 档撤销 temp ACE 并报出所有清理失败；`elevated` 档无物可撤（no-op）。 */
  dispose(): void
}

/**
 * seam 看到的那个 `AclWriteGrant`：**按当前档位分派**（implementation/sandbox-decodex-rename-acl-elevated-modes W4）。
 *
 *  - `acl` ⇒ 上游 `AclWriteGrant.create(writeSid)`（能力 SID 落 ACE；第二个参数被忽略——
 *    上游没有「授给哪个账号」这个概念）。
 *  - `elevated` ⇒ {@link SandboxUserWriteGrant}（沙箱用户承载写权限）。
 *
 * 分派点放在这里而不是让 seam 认识两个名字，是为了让补丁保持最小：seam 的 `import` 语句一个字
 * 都不用改，档位只在设置里换。
 */
export const AclWriteGrant = {
  /**
   * 就绪一个当前档位下的写授权。
   * @param writeSid - 工作区或 temp 的写能力 SID。
   * @param sandboxAccount - 仅提权档有意义（覆盖默认沙箱账号）；其余取值忽略。
   * @returns 满足 {@link WriteGrant} 的实例。
   */
  create(writeSid: string, sandboxAccount?: unknown): WriteGrant {
    if (sandboxMode() === 'acl') return upstreamAcl().AclWriteGrant.create(writeSid) as UpstreamWriteGrant
    return SandboxUserWriteGrant.create(writeSid, typeof sandboxAccount === 'string' ? sandboxAccount : undefined)
  },
}
