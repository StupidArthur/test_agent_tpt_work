/**
* 列出一个插件根下的插件目录（含 `@scope/` 一层）。
*
* 判据只有两条，与 `vendor/dsh-desktop-host` 的枚举同口径：**非点开头的目录** + **目录里有
* `package.json`**。不按包名形状过滤：包名形状在这三颗插件上实测都不止一种（`tools/third-party-plugins`
* 的成表清单就是为这条"推不出"立的账）。
* @param roots - 插件根。
* @param io - 读盘面。
* @returns `{ dir, name }`（`name` = 目录段拼出的候选包名，清单里没有 `name` 时兜底用它）。
*/
function listPluginDirs(roots, io) {
	const out = [];
	const seen = /* @__PURE__ */ new Set();
	/** 一个目录是不是插件目录（有 `package.json`）。 */
	const isPluginDir = (dir) => io.listDir(dir).includes("package.json");
	for (const rawRoot of roots) {
		const root = rawRoot.trim();
		if (root === "") continue;
		for (const entry of io.listDir(root)) {
			if (entry.startsWith(".")) continue;
			const dir = join(root, entry);
			if (!io.isDir(dir)) continue;
			if (entry.startsWith("@")) {
				for (const inner of io.listDir(dir)) {
					if (inner.startsWith(".")) continue;
					const scopedDir = join(dir, inner);
					const name = `${entry}/${inner}`;
					if (seen.has(name) || !io.isDir(scopedDir) || !isPluginDir(scopedDir)) continue;
					seen.add(name);
					out.push({
						dir: scopedDir,
						name
					});
				}
				continue;
			}
			if (seen.has(entry) || !isPluginDir(dir)) continue;
			seen.add(entry);
			out.push({
				dir,
				name: entry
			});
		}
	}
	return out;
}
