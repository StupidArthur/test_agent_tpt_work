/**
* 注册 Remote 服务。本包的 entry 形态是插件（`name`/`inject`/`apply`）而非服务类，故在 `apply` 里
* 实例化服务 —— 与 `@tpt-work/supcon-agents` 同形（`TypertRemoteService` 构造即自注册）。
*
* ⚠ `profileContext` 走 `ctx.inject` 而**不是**构造器里读一次快照：装配顺序不保证本插件与那次
* `provide` 谁先到；等服务到达再写锚，拿不到就永远不写（读侧退化成空表，侧栏按内置表兜底）。
* @param ctx - 宿主 context。
*/
function apply(ctx) {
	const controller = new TptSidebarController(ctx);
	ctx.inject(["profileContext"], (anchorCtx) => {
		controller.useAnchor(anchorCtx.profileContext?.installAnchor);
	});
}
