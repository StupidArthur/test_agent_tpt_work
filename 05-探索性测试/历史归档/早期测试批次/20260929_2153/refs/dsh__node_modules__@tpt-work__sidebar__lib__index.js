/**
* 自动任务目录分配器（宿主侧）。
*
* 用户没手选工作区时，会话落在数据根下的一个独立子目录：
*
* ```
* <TPT_TASKS_DIR>/t-<yyyyMMdd-HHmmss>-<4hex>
* ```
*
* 三条口径的落点：
* - **根从 env 读，不在这里算**。`TPT_TASKS_DIR` 由本包的 {@link materializeDataRoots}
*   （dev/独立跑，经 `packages/host/src/data-home.ts`）与 `packages/data-root/src/desktop-home.ts`
*   （打包态，壳落 env 后由 `host-process.ts` 的透传过滤规则带给宿主子进程）两处写入 ——
*   数据根解析有**唯一权威点**，本文件只是消费方（缺位就抛错，绝不自己拼一个 `~/.tpt-work`：
*   那会在隔离探针里把任务写进真实数据根）。
* - **只算路径 + 建目录，不改任何注册表**。会话拿到这个 `cwd` 后不会被任何 workspace 认领，于是
*   天然属于「没有选择工作区的会话」，正是「最近」面板的取数口径 —— 数据根下的目录**不会**变成
*   【项目】（工作区要 `workspaces.create` 显式建，实测：`<数据根>/tasks/` 下几十条任务会话，
*   工作区登记表里一条都没有）。
* - 目录名纯 ASCII + 连字符：它在磁盘上是 agent 的可写根，同时也是 `sessions/<projectKey>` 分片名
*   的来源（上游 `projectKey` 会把分隔符换成 `-`），别放中文/空格去考验那套转义。
*
* 时间戳用本地时区且不含 `:`（Windows 文件名禁），故 `t-20260914-153012-a1b2` 这种形状在三个平台
* 都合法；同秒重复点新建由 4 位十六进制随机 + 撞名重开一次兜住。
*
* ⚠ **为什么这一份住在数据根包**（七十一改版 C 案的后续，需求方 2026-09-22）：原本它在
* `packages/sidebar/src/task-dir.ts`（十一改版，那时只有侧栏「新建任务」一个消费方）。随后
* **自动化任务**（`@tpt-work/automation` 的执行器）也要给"没绑项目的定时任务运行"一个落点 ——
* 第二消费方一出现，目录名的口径与 `TPT_TASKS_DIR` 这个 env 键就必须只有一个家（R10）⇒ 整套搬进
* 本包（它已经拥有 `TASKS_DIR_NAME` / `tasksDir` / 写 env 那一步），侧栏改为从这里 import 并原样
* 再导出（对外名字一个没变）。
*/
/** 承载根的 env 键（写入方见文件头；与本包 `materializeDataRoots` 同名）。 */
const TASKS_DIR_ENV = "TPT_TASKS_DIR";
/** 撞名重开的上限：同一秒内并发新建才会撞上，5 次足够（撞上就 fail loud，不静默共用目录）。 */
const ALLOCATE_ATTEMPTS = 5;
/** 分配失败（承载根缺位/非法，或连续撞名）。 */
var TaskDirError = class extends Error {
	/**
	* @param message - 人话原因（会原样过 wire 到浏览器半）。
	*/
	constructor(message) {
		super(message);
		this.name = "TaskDirError";
	}
};
/** 补零到两位。 */
function pad(value) {
	return String(value).padStart(2, "0");
}
/**
* 目录名 = `t-<yyyyMMdd>-<HHmmss>-<rand>`（本地时区，无非法文件名或路径分隔符字符）。
* @param now - 分配时刻。
* @param rand - 随机尾巴（调用方给，便于测试注入）。
* @returns 目录名。
*/
function taskDirName(now, rand) {
	return `t-${`${String(now.getFullYear())}${pad(now.getMonth() + 1)}${pad(now.getDate())}`}-${`${pad(now.getHours())}${pad(now.getMinutes())}${pad(now.getSeconds())}`}-${rand}`;
}
/**
* 读承载根。**缺位/空串/纯空白都算未设并抛错**（与本包 `nonBlank` 同口径）：
* 这里绝不回落家目录 —— 静默回落会让隔离环境把任务写进真实 `~/.tpt-work`。
* @param env - 环境读数（默认 `process.env`，测试注入）。
* @returns 承载根绝对路径。
* @throws {TaskDirError} 未设时。
*/
function readTasksRoot(env = process.env) {
	const raw = env[TASKS_DIR_ENV];
	if (raw === void 0 || raw.trim() === "") throw new TaskDirError(`${TASKS_DIR_ENV} 未设：自动任务目录的承载根缺失（宿主数据根未落到 env）`);
	return raw;
}
/**
* 分配一个新任务目录：算名 -> 建目录 -> 撞名则换随机尾巴重来。
*
* 根用 `recursive` 建（首启时 `tasks/` 还不存在），叶子目录**不** recursive：撞名必须显式失败
* 才能重开，recursive 会把 EEXIST 吞成成功、两个任务共用一个目录。
* @param options - 可注入环节。
* @returns 分配结果。
* @throws {TaskDirError} 承载根缺位，或连续 {@link ALLOCATE_ATTEMPTS} 次撞名。
*/
function allocateTaskDir(options = {}) {
	const env = options.env ?? process.env;
	const now = options.now ?? /* @__PURE__ */ new Date();
	const mkdir = options.mkdir ?? ((target, recursive) => {
		mkdirSync(target, { recursive });
	});
	const root = readTasksRoot(env);
	mkdir(root, true);
	let rand = options.rand ?? randomBytes(2).toString("hex");
	for (let attempt = 0; attempt < ALLOCATE_ATTEMPTS; attempt += 1) {
		const name = taskDirName(now, rand);
		const path = join(root, name);
		try {
			mkdir(path, false);
			return {
				root,
				path,
				name
			};
		} catch (error) {
			if (error.code !== "EEXIST") throw new TaskDirError(`建任务目录失败 ${path}: ${String(error)}`);
			rand = randomBytes(2).toString("hex");
		}
	}
	throw new TaskDirError(`连续 ${String(ALLOCATE_ATTEMPTS)} 次任务目录撞名，放弃（root=${root}）`);
}
