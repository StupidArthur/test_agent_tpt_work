/**
* 解析 `label`：字符串或 `{zh,en}`（至少一个非空）。
* @param value - 清单里的原值。
* @returns 声明文案；取不到则 undefined。
*/
function readLabel(value) {
	const single = nonBlank(value);
	if (single !== void 0) return single;
	if (value === null || typeof value !== "object" || Array.isArray(value)) return void 0;
	const source = value;
	const zh = nonBlank(source.zh);
	const en = nonBlank(source.en);
	if (zh === void 0 && en === void 0) return void 0;
	const out = {};
	if (zh !== void 0) out.zh = zh;
	if (en !== void 0) out.en = en;
	return out;
}
/**
* 解析 `shapes`：只留非空字符串、去重、保序（**不在这里做窄并集降级**：在册位子随产品版本变，
* 判据归浏览器半，见 `plugin-seat-decls.resolveSeatPlans`）。
* @param value - 清单里的原值。
* @returns 位子串列表；一个都不剩则 undefined。
*/
function readShapes(value) {
	if (!Array.isArray(value)) return void 0;
	const out = [];
	for (const item of value) {
		const shape = nonBlank(item);
		if (shape !== void 0 && !out.includes(shape)) out.push(shape);
	}
	return out.length > 0 ? out : void 0;
}
/**
* 把插件声明的图标路径读成 `data:` URL（**收口点**）。
*
* 六道判据，任一不过就丢图标字段（调用方照常出那一行，只是没有图标）：路径是包内相对路径、不含 `..`、
* 扩展名在册、解析后仍在包根之内、文件读得到、体积不超上限。
* @param pkgDir - 插件包根绝对路径。
* @param declared - 清单里 `tpt.seat.icon` 的原值（作者写的是包内相对路径）。
* @param io - 读盘面。
* @param maxBytes - 体积上限（字节）。
* @returns `data:` URL；不合规/读不到则 undefined。
*/
function readIconDataUrl(pkgDir, declared, io, maxBytes = ICON_MAX_BYTES) {
	const rel = nonBlank(declared);
	if (rel === void 0 || rel.length > ICON_PATH_MAX) return void 0;
	if (rel.startsWith("/") || rel.includes("\\") || rel.includes("\0")) return void 0;
	const segments = rel.split("/");
	if (segments.some((segment) => segment === "" || segment === "." || segment === "..")) return void 0;
	const mime = ICON_MIME[extname(rel).toLowerCase()];
	if (mime === void 0) return void 0;
	const root = resolve(pkgDir);
	const abs = resolve(root, ...segments);
	if (abs !== root && !abs.startsWith(`${root}${sep}`)) return void 0;
	const bytes = io.readBytes(abs);
	if (bytes === void 0 || bytes.byteLength === 0 || bytes.byteLength > maxBytes) return void 0;
	return `data:${mime};base64,${Buffer.from(bytes).toString("base64")}`;
}
/**
* 读一个行序权重（`tpt.seat.order`）。
* @param value - 清单里的原值。
* @returns 有限数；`NaN` / `±Infinity` / 非数一律 undefined（= 没声明，走默认权重）。
*/
function readOrder(value) {
	return typeof value === "number" && Number.isFinite(value) ? value : void 0;
}
/**
* 读一个插件包的 `tpt.seat`（**清单只读、逐字段宽容**）。
* @param pkgDir - 插件包根绝对路径。
* @param io - 读盘面。
* @param iconMaxBytes - 图标体积上限（字节）。
* @returns 声明；一个可用字段都没有则 undefined（= 这包没声明）。
*/
function readSeatDecl(pkgDir, io, iconMaxBytes = ICON_MAX_BYTES) {
	const text = io.readText(join(pkgDir, "package.json"));
	if (text === void 0) return void 0;
	let parsed;
	try {
		parsed = JSON.parse(text);
	} catch {
		return;
	}
	if (parsed === null || typeof parsed !== "object" || Array.isArray(parsed)) return void 0;
	const seat = parsed.tpt?.seat;
	if (seat === null || typeof seat !== "object" || Array.isArray(seat)) return void 0;
	const source = seat;
	const out = {};
	const entryIds = readEntryIds(source.entryIds);
	if (entryIds !== void 0) out.entryIds = entryIds;
	const label = readLabel(source.label);
	if (label !== void 0) out.label = label;
	const shapes = readShapes(source.shapes);
	if (shapes !== void 0) out.shapes = shapes;
	const tab = nonBlank(source.tab);
	if (tab !== void 0) out.tab = tab;
	const order = readOrder(source.order);
	if (order !== void 0) out.order = order;
	const prefix = readSessionPrefixes(source.sessionIdPrefixes);
	if (prefix !== void 0) out.sessionIdPrefixes = prefix;
	const slot = nonBlank(source.slot);
	if (slot !== void 0) out.slot = slot;
	const route = nonBlank(source.route);
	if (route !== void 0 && route.startsWith("/")) out.route = route;
	const icon = readIconDataUrl(pkgDir, source.icon, io, iconMaxBytes);
	if (icon !== void 0) out.icon = icon;
	return Object.keys(out).length > 0 ? out : void 0;
}
/**
* 读全部已装插件的席位声明。
*
* ⚠ **没声明 `tpt.seat` 的包也会出一行**（`seat` 缺位）：ADR-026 的合并链靠"这包装了什么"来给内置表
* 兜底、并给没有路由的包探一次 UI 路由；把没声明的包滤掉会让那条链只对自报的包生效。行的顺序 = 枚举
* 顺序（root 优先序 × 目录读序），浏览器半还会按包名重排，故这里不排。
* @param options - 见 {@link ReadSeatDeclsOptions}。
* @returns 行数组；任何失败都折成"少几行"，**永不抛**。
*/
function readSeatDecls(options) {
	const io = options.io ?? createSeatDeclIo();
	const maxBytes = options.iconMaxBytes ?? 65536;
	const out = [];
	for (const entry of listPluginDirs(options.roots, io)) {
		const text = io.readText(join(entry.dir, "package.json"));
		const row = { package: (text === void 0 ? void 0 : readManifestName(text)) ?? entry.name };
		const seat = readSeatDecl(entry.dir, io, maxBytes);
		if (seat !== void 0) row.seat = seat;
		out.push(row);
	}
	return out;
}
/**
* 从清单文本里取 `name`（取不到返回 undefined，调用方回落到目录段拼出的候选包名）。
* @param text - `package.json` 文本。
* @returns 包名。
*/
function readManifestName(text) {
	try {
		return nonBlank(JSON.parse(text).name);
	} catch {
		return;
	}
}
/**
* 从宿主 `profileContext.installAnchor` 派生插件根（**唯一权威来源 = 加载器那一侧**）。
*
* 锚的判据与 `packages/host/src/prebundle-loader.ts` 的 `pluginsRootIn`、
* `vendor/dsh-desktop/src/scripts/resources-manifest-seats.ts` 对同一锚的读法一致：安装锚那份
* `package.json` 所在的目录就是资源根，插件字节住在它下面的 `plugins/<族>/<名>/`。
* **`third_party` 在前**：同名的第三方件与随包件同时在场时，用户自己装的优先。
* @param installAnchor - `profileContext.installAnchor`（安装锚那份 `package.json` 的路径）。
* @returns 插件根数组（锚不可用 ⇒ 空数组 ⇒ 读侧整体退化成"没有契约"）。
*/
function pluginRootsFromAnchor(installAnchor) {
	const anchor = nonBlank(installAnchor);
	if (anchor === void 0) return [];
	const root = resolve(anchor);
	const base = root.endsWith("package.json") ? resolve(root, "..") : root;
	return [join(base, "plugins", "third_party"), join(base, "plugins", "builtin")];
}
