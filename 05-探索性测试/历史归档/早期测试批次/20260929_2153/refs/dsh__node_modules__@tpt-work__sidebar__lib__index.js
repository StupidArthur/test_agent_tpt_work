/**
* 新建项目目录分配器（宿主侧，implementation/new-project-dialog-shadcn-dialog-field 七十一改版）。
*
* 用户 2026-09-22 的口径：「新建项目的弹窗里，选择文件夹改成非必填」，默认落点按需求方拍板的
* **方案 A** 收在这里的一个子目录：
*
* ```
* <TPT_PROJECTS_DIR>/<项目名>
* ```
*
* 为什么不落系统「文档」目录、也不落家目录：那两条都要在壳与宿主两侧各自解析跨平台的用户目录
* （多一份解析副本，见 `docs/` 的一条事实一个家），而且会**绕开 TPT_HOME 隔离链** —— 隔离探针
* （`TPT_HOME` 指到临时目录）里点一下新建项目就写进真实用户目录，正是 R8 要防的那类事故。
* 数据根方案天然继承隔离：`TPT_HOME` 一拧，任务、dsh 数据、项目三样一起进隔离目录。
*
* 三条口径的落点：
* - **根从 env 读，不在这里算**（与 {@link ./task-dir.ts} 同一条姿态）。`TPT_PROJECTS_DIR` 由
*   `packages/host/src/data-home.ts::applyDataRoots`（dev/独立跑）与
*   `packages/data-root/src/desktop-home.ts::applyTptRoots`（打包态）两处写入；本文件只是消费方，
*   缺位就抛错，绝不自己拼一个 `~/.tpt-work`。
* - **目录名 = 项目名**（用户视角最直观：弹窗里看到的默认位置就是 `<根>/<我起的名字>`），非法文件名字符
*   换成连字符。重名冲突不在这里挡：同名项目早被弹窗的「已在册」判据拦住（项目名唯一），
*   已存在的同名文件夹则直接复用（`recursive` 建，见 {@link allocateProjectDir}）。
* - **只算路径 + 建目录，不改任何注册表**：加进【项目】面板那一步仍归上游
*   `workspaces.create({ path })`（浏览器半 `client.tsx` 的 `createProject`），本文件不碰工作区名册。
*/
/** 承载根的 env 键（写入方见文件头；与 `data-root` 的 `TPT_PROJECTS_DIR` 同名）。 */
const PROJECTS_DIR_ENV = "TPT_PROJECTS_DIR";
/** Windows 文件名非法字符（跨平台安全起见，三平台一律替换）。 */
const ILLEGAL_NAME_CHARS = /[\\/:*?"<>|]/g;
/**
* 控制字符（含 `\n` / `\t` / NUL）：终端里贴进来的名字常带这些，落盘前一律清掉。
*
* 规则放行是**有意**的：这条正则要匹配的就是控制字符本身（与"误把控制字符写进匹配模式"是两回事）。
*/
const CONTROL_CHARS = /[\u0000-\u001f\u007f]/g;
/** 分配失败（承载根缺位/非法，或项目名清洗后为空，或建目录真失败）。 */
var ProjectDirError = class extends Error {
	/**
	* @param message - 人话原因（会原样过 wire 到浏览器半，弹窗直接显示）。
	*/
	constructor(message) {
		super(message);
		this.name = "ProjectDirError";
	}
};
/**
* 读承载根。**缺位/空串/纯空白都算未设并抛错**（与 `data-home.ts::nonBlank` 同口径）：
* 绝不回落家目录 —— 静默回落会让隔离环境把项目写进真实 `~/.tpt-work`。
* @param env - 环境读数（默认 `process.env`，测试注入）。
* @returns 承载根绝对路径。
* @throws {ProjectDirError} 未设时。
*/
function readProjectsRoot(env = process.env) {
	const raw = env[PROJECTS_DIR_ENV];
	if (raw === void 0 || raw.trim() === "") throw new ProjectDirError(`${PROJECTS_DIR_ENV} 未设：默认项目文件夹的承载根缺失（宿主数据根未落到 env）`);
	return raw;
}
/**
* 项目名 -> 目录名。规则四条（顺序即判据）：
* ① 去首尾空白；② 非法文件名字符与控制字符换成 `-`；③ 去掉结尾的点与空格（Windows 上 `foo.` 与
* `foo ` 是同一个目录名，留着会让"显示的名字"与"磁盘上的名字"悄悄不一致）；④ 结果为空则抛错
* （项目名全是 `???` 这种）。
* @param raw - 用户给的项目名。
* @returns 可直接当目录名的串。
* @throws {ProjectDirError} 清洗后为空时。
*/
function projectDirName(raw) {
	const cleaned = raw.trim().replace(ILLEGAL_NAME_CHARS, "-").replace(CONTROL_CHARS, "-").replace(/[. ]+$/, "");
	if (cleaned === "") throw new ProjectDirError("项目名不能作为文件夹名，请换一个名字或手动选择文件夹");
	return cleaned;
}
/**
* 按项目名分配默认项目目录：算名 -> 建根 -> 建叶子。
*
* 叶子用 `recursive: true`（与 `allocateTaskDir` **刻意相反**）：任务目录要求"一次一目录、撞名必须重开"，
* 而项目目录要求"名字即身份、已存在就复用它" —— 用户建过一次的项目再建（或上次创建失败后重试），
* 复用一个空目录才是期望行为，报 EEXIST 反而挡住了正常路径。真失败（权限、路径过长、同名文件）原样抛。
* @param name - 项目名（原始输入，内部清洗）。
* @param options - 可注入环节。
* @returns 分配结果。
* @throws {ProjectDirError} 承载根缺位、项目名不可用，或建目录失败。
*/
function allocateProjectDir(name, options = {}) {
	const env = options.env ?? process.env;
	const mkdir = options.mkdir ?? ((target, recursive) => {
		mkdirSync(target, { recursive });
	});
	const root = readProjectsRoot(env);
	const dirName = projectDirName(name);
	const path = join(root, dirName);
	try {
		mkdir(root, true);
		mkdir(path, true);
	} catch (error) {
		throw new ProjectDirError(`建项目文件夹失败 ${path}: ${String(error)}`);
	}
	return {
		root,
		path,
		name: dirName
	};
}
