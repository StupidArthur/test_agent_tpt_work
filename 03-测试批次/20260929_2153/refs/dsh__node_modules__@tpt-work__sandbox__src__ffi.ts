/**
 * codex FFI 管道 host（koffi 直调 kernel32，替代 .NET codex-bridge）。
 *
 * codex `ipc_framed` 要求父进程当字节模式命名管道 server：建 `-in`/`-out` 两条管道，
 * runner（以原生 CreateFileW 客户端）连上来；父进程向 `-in` 写请求帧、从 `-out` 读输出帧。
 * Node `net` 建不出能正确与原生客户端互操作的字节模式管道（见 implementation/codex-sandbox-package-first-tranche Round 3 探针），
 * 故用 koffi 直调 `CreateNamedPipeW`/`ConnectNamedPipe`/`WriteFile`/`ReadFile` 拿回原生字节语义。
 *
 * ⚠ 管道以 **FILE_FLAG_OVERLAPPED** 创建（2026-09-13 评审 medium）：同步 ConnectNamedPipe 在
 * 客户端不连入时永久阻塞，`Date.now()` 死限在阻塞期到不了 ⇒ runner 起而未连（版本漂移/启动后
 * 崩溃）时包装进程挂死。改 overlapped 后 `ConnectNamedPipe` 立即返回 IO_PENDING，真实死限由
 * `WaitForSingleObject(剩余毫秒)` 执行，到点 CancelIoEx 收尾并 fail-loud 抛错。
 * ReadFile/WriteFile 因此也必须带 OVERLAPPED（overlapped 句柄 + NULL overlapped 未定义）；
 * 读循环的线程池等待分支从「阻塞 ReadFile 下线程池」换成「ReadFile + WaitForSingleObject.async
 * (事件)」，事件循环依旧不被阻塞（koffi `.async` 同一先例）。
 * @module
 */

import { randomBytes } from 'node:crypto'
import koffi from 'koffi'
import { lazily, loadWin32Library } from './win32-load.ts'

// ⚠ DLL 装载与函数绑定一律惰性（`xxx()` 先取绑定再调用，memo 化只装载一次）：
// 本包的 `index` 被 `dsh-sandbox-local` 静态 import，而后者是各平台常驻 entry ⇒ 顶层
// `koffi.load('kernel32.dll')` 会让非 Windows 的 backend 连装配都过不去。缘由与语义等价处理见 `win32-load.ts`。
const K = lazily(() => loadWin32Library('kernel32.dll'))

// koffi 结构体注册留在模块顶层（纯 JS 侧类型登记、跨平台安全，且必须早于引用类型名的 `.func()` 原型解析）。
// ⚠ 打包态本包可能同进程加载两次（提升份 + 嵌套份），koffi 类型注册是进程全局 ⇒ 幂等注册、
// 之后一律用类型名字符串（win32.ts 同款）。
function registerStruct(name: string, shape: Record<string, string>): void {
  try {
    koffi.struct(name, shape)
  } catch {
    /* 已注册（同一进程里本包被加载了两次）：复用 */
  }
}

// OVERLAPPED（x64 布局共 32 字节）：我们只消费 hEvent，其余字段保留占位，且**每次发起 IO 前
// 必须整体清零重挂事件**（系统会在上次 IO 里回写 Internal/InternalHigh）。
registerStruct('TPT_OVERLAPPED', {
  Internal: 'uintptr_t',
  InternalHigh: 'uintptr_t',
  Offset: 'uint32',
  OffsetHigh: 'uint32',
  hEvent: 'void*',
})

const CreateNamedPipeW = lazily(() => K().func('void* CreateNamedPipeW(wchar_t* name, uint openMode, uint pipeMode, uint maxInstances, uint outBuf, uint inBuf, uint timeout, void* secAttr)'))
const ConnectNamedPipe = lazily(() => K().func('int ConnectNamedPipe(void* pipe, TPT_OVERLAPPED* overlapped)'))
const WriteFileFn = lazily(() => K().func('int WriteFile(void* h, void* buffer, uint bytes, void* written, TPT_OVERLAPPED* overlapped)'))
const ReadFileFn = lazily(() => K().func('int ReadFile(void* h, void* buffer, uint bytes, void* read, TPT_OVERLAPPED* overlapped)'))
const CloseHandle = lazily(() => K().func('int CloseHandle(void* h)'))
const GetLastError = lazily(() => K().func('uint GetLastError()'))
const CreateEventW = lazily(() => K().func('void* CreateEventW(void* attrs, int manualReset, int initialState, wchar_t* name)'))
const WaitForSingleObject = lazily(() => K().func('uint WaitForSingleObject(void* h, uint ms)'))
const GetOverlappedResult = lazily(() => K().func('int GetOverlappedResult(void* h, TPT_OVERLAPPED* overlapped, void* bytes, int wait)'))
const CancelIoEx = lazily(() => K().func('int CancelIoEx(void* h, TPT_OVERLAPPED* overlapped)'))

export const PIPE_ACCESS_DUPLEX = 0x3
export const PIPE_BYTE_MODE = 0x0 // PIPE_TYPE_BYTE | PIPE_READMODE_BYTE
/** FILE_FLAG_OVERLAPPED：overlapped 管道句柄（ConnectNamedPipe/ReadFile/WriteFile 全部带 OVERLAPPED）。 */
export const FILE_FLAG_OVERLAPPED = 0x40000000
const ERROR_IO_PENDING = 997
const ERROR_PIPE_CONNECTED = 535
const WAIT_OBJECT_0 = 0
const WAIT_TIMEOUT = 0x102
const INVALID_PIPE = -1

export interface PipePair {
  hIn: unknown
  hOut: unknown
  pipeInPath: string
  pipeOutPath: string
}

/** 分配一个清零的 OVERLAPPED 并挂上 event（复用前须 `resetOverlapped`）。 */
function makeOverlapped(event: unknown): unknown {
  const ol = koffi.alloc('TPT_OVERLAPPED', 1)
  resetOverlapped(ol, event)
  return ol
}

/** 重置 OVERLAPPED（清零系统回写字段 + 重挂事件；串行复用同一块内存）。 */
function resetOverlapped(ol: unknown, event: unknown): void {
  koffi.encode(ol, 'TPT_OVERLAPPED', { Internal: 0, InternalHigh: 0, Offset: 0, OffsetHigh: 0, hEvent: event })
}

/** 建一个自动复位事件（overlapped 完成信号）。 */
function makeEvent(): unknown {
  const event = CreateEventW()(null, 0, 0, null)
  if (!event) throw new Error(`CreateEventW failed err=${GetLastError()()}`)
  return event
}

/** 尽力而为关句柄。 */
function closeQuietly(handle: unknown): void {
  try { CloseHandle()(handle) } catch { /* 忽略 */ }
}

/** koffi 线程池等待（主事件循环不阻塞）；resolve WaitForSingleObject 的原生返回值。 */
function waitHandleAsync(handle: unknown, ms: number): Promise<number> {
  return new Promise((resolve, reject) => {
    WaitForSingleObject().async(handle, ms, (err: unknown, result: unknown) => {
      if (err) reject(err)
      else resolve(result as number)
    })
  })
}

function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => { setTimeout(resolve, ms) })
}

/** 建两条字节模式命名管道（server 端，overlapped）。`secAttr` 非空时用它给管道设 DACL（提权路径需授沙箱用户）。 */
export function createPipePair(prefix = 'codex-ffi', secAttr: unknown = null): PipePair {
  const nonce = `${prefix}-${randomBytes(6).toString('hex')}`
  const pipeInPath = `\\\\.\\pipe\\${nonce}-in`
  const pipeOutPath = `\\\\.\\pipe\\${nonce}-out`
  const openMode = PIPE_ACCESS_DUPLEX | FILE_FLAG_OVERLAPPED
  const hIn = CreateNamedPipeW()(pipeInPath, openMode, PIPE_BYTE_MODE, 1, 65536, 65536, 0, secAttr)
  const hOut = CreateNamedPipeW()(pipeOutPath, openMode, PIPE_BYTE_MODE, 1, 65536, 65536, 0, secAttr)
  if (hIn === null || hOut === null || hIn === INVALID_PIPE || hOut === INVALID_PIPE) {
    throw new Error(`CreateNamedPipeW failed err=${GetLastError()()}`)
  }
  return { hIn, hOut, pipeInPath, pipeOutPath }
}

/**
 * 等 runner 连上两条管道（spawn runner 后调用）。
 *
 * ⚠ **到点 fail-loud**（2026-09-13 评审 medium）：overlapped `ConnectNamedPipe` 立即返回，
 * 真实死限由 `WaitForSingleObject(剩余毫秒)` 执行——旧同步实现的 `Date.now()` 检查在阻塞期
 * 永远到不了。超时先 `CancelIoEx` 收尾（aborted 完成分支落地后句柄才可安全关闭）再抛错。
 * 未知错误分支退避 25ms 重试到 deadline（禁热自旋）。
 */
export async function waitForConnections(pair: PipePair, timeoutMs = 15_000): Promise<void> {
  const deadline = Date.now() + timeoutMs
  for (const h of [pair.hIn, pair.hOut]) {
    await connectOne(h, deadline)
  }
}

/** 单条管道的连接等待：overlapped ConnectNamedPipe + 有限等待 + 到点 fail-loud。 */
async function connectOne(h: unknown, deadline: number): Promise<void> {
  const budgetMs = Math.max(0, deadline - Date.now())
  const event = makeEvent()
  try {
    for (;;) {
      const ol = makeOverlapped(event)
      const ok = ConnectNamedPipe()(h, ol)
      if (ok) break // 客户端已连入（同步完成）
      const err = GetLastError()() // 同线程紧随其后 ⇒ thread-local 读数有效
      if (err === ERROR_PIPE_CONNECTED) break
      if (err !== ERROR_IO_PENDING) {
        if (Date.now() >= deadline) throw new Error(`pipe connect timeout (last err=${err})`)
        await sleep(25) // 退避重试，禁热自旋
        continue
      }
      const remaining = deadline - Date.now()
      if (remaining <= 0) {
        await cancelPending(h, ol, event)
        throw new Error(`pipe connect timeout after ${budgetMs}ms（runner 未连入管道）`)
      }
      const wait = await waitHandleAsync(event, remaining)
      if (wait === WAIT_OBJECT_0) {
        const got = koffi.alloc('uint', 1)
        if (GetOverlappedResult()(h, ol, got, 0)) break
        const gerr = GetLastError()()
        if (gerr === ERROR_PIPE_CONNECTED) break
        if (Date.now() >= deadline) throw new Error(`pipe connect failed err=${gerr}`)
        await sleep(25)
        continue
      }
      if (wait === WAIT_TIMEOUT) {
        await cancelPending(h, ol, event)
        throw new Error(`pipe connect timeout after ${budgetMs}ms（runner 未连入管道）`)
      }
      throw new Error(`WaitForSingleObject(pipe connect) failed wait=${wait} err=${GetLastError()()}`)
    }
  } finally {
    closeQuietly(event)
  }
}

/** 取消一笔未完成的 overlapped 连接并等其 aborted 完成分支落地（之后句柄才可安全关闭）。 */
async function cancelPending(h: unknown, ol: unknown, event: unknown): Promise<void> {
  try {
    CancelIoEx()(h, ol)
  } catch {
    /* 尽力而为 */
  }
  const drained = await waitHandleAsync(event, 1_000)
  if (drained === WAIT_OBJECT_0) {
    // 消费 aborted 完成状态，结果本身无所谓。
    GetOverlappedResult()(h, ol, koffi.alloc('uint', 1), 0)
  }
}

/** 把 JSON 请求帧包成 wire 帧（[4 字节 LE 长度头][JSON]；runner 的 read_frame 按此切）。 */
export function toWire(json: string): Buffer {
  const payload = Buffer.from(json, 'utf8')
  const wire = Buffer.alloc(4 + payload.length)
  wire.writeUInt32LE(payload.length, 0)
  payload.copy(wire, 4)
  return wire
}

/**
 * 向 `-in` 写一个 wire 帧（SpawnRequest / Stdin / CloseStdin / Resize / Terminate）。
 * ⚠ 管道为 overlapped 句柄 ⇒ WriteFile 必须带 OVERLAPPED（NULL 未定义）。帧远小于管道缓冲，
 * 几乎总同步完成；IO_PENDING 分支用事件等满——本函数保持**同步**语义（SIGTERM 处理器里同步调用）。
 */
export function writeWire(pair: PipePair, wire: Buffer): void {
  const kb = koffi.alloc('uchar', wire.length)
  // ⚠ 用 `koffi.encode` 而非 `koffi.view`：view 依赖 external ArrayBuffer，Electron utilityProcess
  // 禁止 ⇒ `napi_fatal_error` 整进程 abort（exit 134）。
  koffi.encode(kb, 'uint8', wire, wire.length)
  const written = koffi.alloc('uint', 1)
  const event = makeEvent()
  try {
    const ol = makeOverlapped(event)
    const ok = WriteFileFn()(pair.hIn, kb, wire.length, written, ol)
    if (!ok) {
      const err = GetLastError()()
      if (err !== ERROR_IO_PENDING) throw new Error(`WriteFile(-in) failed err=${err}`)
      if (WaitForSingleObject()(event, 0xffffffff) !== WAIT_OBJECT_0) {
        throw new Error(`WriteFile(-in) wait failed err=${GetLastError()()}`)
      }
      if (!GetOverlappedResult()(pair.hIn, ol, written, 0)) {
        throw new Error(`WriteFile(-in) result failed err=${GetLastError()()}`)
      }
    }
  } finally {
    closeQuietly(event)
  }
}

type Pointer = unknown

/** 用 koffi 原生缓冲承载待读内存。 */
function allocBuf(size: number): { ptr: unknown; nRead: Pointer } {
  return { ptr: koffi.alloc('uchar', size), nRead: koffi.alloc('uint', 1) as Pointer }
}

/** 拷贝 koffi 缓冲的前 len 字节为 Node Buffer。 */
function copyOut(ptr: unknown, len: number): Buffer {
  return Buffer.from(koffi.decode(ptr, 'uchar', len))
}

/**
 * 从 `-out` 链式读输出帧字节并回调。每个 chunk 交给 frameDecoder 解析。
 * 返回一个停止函数；EOF/错误时自动停。
 *
 * ⚠ overlapped 句柄的读法：ReadFile 立即返回（IO_PENDING），完成等待经
 * `WaitForSingleObject.async`（koffi 线程池，事件循环不阻塞——与旧版「阻塞 ReadFile 下线程池」
 * 等效），完成后再 GetOverlappedResult 取字节数。OVERLAPPED 串行复用：上一笔完成后才发下一笔。
 */
export function startReadLoop(
  hOut: unknown,
  onChunk: (bytes: Buffer) => void,
  onStop: (reason: 'eof' | 'error', code?: number) => void,
): () => void {
  const MAX = 65536
  const { ptr, nRead } = allocBuf(MAX)
  let event: unknown
  try {
    event = makeEvent()
  } catch {
    onStop('error')
    return () => {}
  }
  const ol = makeOverlapped(event)
  let stopped = false
  let eventClosed = false
  const closeEvent = (): void => {
    if (!eventClosed) {
      eventClosed = true
      closeQuietly(event)
    }
  }
  const stop = (): void => {
    stopped = true
    closeEvent()
  }
  const finish = (reason: 'eof' | 'error', code?: number): void => {
    stopped = true
    closeEvent()
    onStop(reason, code)
  }
  const deliver = (): void => {
    const n = koffi.decode(nRead, 'uint') as number
    if (n === 0) {
      finish('eof')
      return
    }
    onChunk(copyOut(ptr, n))
    step()
  }
  const step = (): void => {
    if (stopped) return
    resetOverlapped(ol, event)
    const ok = ReadFileFn()(hOut, ptr, MAX, nRead, ol)
    if (ok) {
      // 同步完成（overlapped 句柄上数据已在缓冲时可能出现）：microtask 交付，避免连击时递归加深。
      queueMicrotask(() => { if (!stopped) deliver() })
      return
    }
    const err = GetLastError()()
    if (err !== ERROR_IO_PENDING) {
      finish('error', err)
      return
    }
    WaitForSingleObject().async(event, 0xffffffff, (waitErr: unknown, waitResult: unknown) => {
      if (stopped) {
        closeEvent()
        return
      }
      if (waitErr || (waitResult as number) !== WAIT_OBJECT_0) {
        finish('error')
        return
      }
      if (!GetOverlappedResult()(hOut, ol, nRead, 0)) {
        finish('error', GetLastError()())
        return
      }
      deliver()
    })
  }
  step()
  return stop
}

/** 关闭两条管道句柄。 */
export function closeHandles(pair: PipePair): void {
  try { CloseHandle()(pair.hIn) } catch { /* 忽略 */ }
  try { CloseHandle()(pair.hOut) } catch { /* 忽略 */ }
}
