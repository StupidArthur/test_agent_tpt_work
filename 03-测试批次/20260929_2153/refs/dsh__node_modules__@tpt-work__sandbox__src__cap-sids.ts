/**
 * codex 能力 SID（cap SID）读取（research/codex-elevated-sandbox-blueprint 提权路径）。
 *
 * codex 把每个工作区/写根的能力 SID 持久化在 `<codex_home>/cap_sid`（JSON），形状
 * `{workspace, readonly, workspace_by_cwd:{<canonicalKey>:sid}, writable_root_by_path:{…}}`，
 * 每个 SID 是**域账号形** `S-1-5-21-<4×u32>`（`cap.rs:make_random_cap_sid_string`）。
 *
 * 提权路径的写隔离靠「受限 token 的 restricting SID 交集」：setup 把写 ACE 授给
 * `workspace_write_cap_sid_for_root(codex_home, cwd, root)`，而 runner 只有把**同一个** SID 放进
 * `cap_sids` 时，workspace-write 的 token 才带上它 ⇒ 写生效；read-only 的 token 不带 ⇒ 写被拒。
 * 因此 SpawnRequest 的 cap_sids **不能**用 dsh 的 `S-1-4-…`（非域形，且 setup 没授过它），
 * 必须用本模块从 cap_sid 文件读出的 codex SID。
 * @module
 */

import { existsSync, readFileSync, realpathSync } from 'node:fs'
import { join } from 'node:path'

interface CapSidsFile {
  workspace?: unknown
  readonly?: unknown
  workspace_by_cwd?: Record<string, unknown>
  writable_root_by_path?: Record<string, unknown>
}

/** codex cap SID 持久化文件（`cap.rs:cap_sid_file`）。 */
export function capSidFilePath(sandboxHome: string): string {
  return join(sandboxHome, 'cap_sid')
}

/**
 * codex `canonical_path_key`：realpath → 反斜杠转正斜杠 → 小写。
 * 路径不存在时退回原串（与 codex `canonicalize_path` 的 unwrap_or_else 同口径）。
 */
export function canonicalPathKey(path: string): string {
  let real: string
  try {
    real = realpathSync.native(path)
  } catch {
    real = path
  }
  return real.replaceAll('\\', '/').toLowerCase()
}

function readCapSids(sandboxHome: string): CapSidsFile | undefined {
  const file = capSidFilePath(sandboxHome)
  if (!existsSync(file)) return undefined
  try {
    return JSON.parse(readFileSync(file, 'utf8')) as CapSidsFile
  } catch {
    return undefined
  }
}

/**
 * 工作区/写根的能力 SID（`cap.rs:workspace_write_cap_sid_for_root` 同口径）：
 * root == cwd ⇒ `workspace_by_cwd[key(cwd)]`，否则 `writable_root_by_path[key(root)]`。
 * @returns SID 字符串；cap_sid 文件缺失或键不存在时 undefined（调用方 fail-closed）。
 */
export function workspaceWriteCapSid(sandboxHome: string, cwd: string, root: string): string | undefined {
  const caps = readCapSids(sandboxHome)
  if (caps === undefined) return undefined
  const map = canonicalPathKey(root) === canonicalPathKey(cwd) ? caps.workspace_by_cwd : caps.writable_root_by_path
  const sid = map?.[canonicalPathKey(root)]
  return typeof sid === 'string' && sid.length > 0 ? sid : undefined
}

/** 只读能力 SID（`cap.rs` 的 `readonly` 字段）。 */
export function readOnlyCapSidFromFile(sandboxHome: string): string | undefined {
  const sid = readCapSids(sandboxHome)?.readonly
  return typeof sid === 'string' && sid.length > 0 ? sid : undefined
}

/** cap_sid 文件是否存在且可解析（提权路径前置条件之一）。 */
export function capSidsPresent(sandboxHome: string): boolean {
  const caps = readCapSids(sandboxHome)
  return caps !== undefined && typeof caps.readonly === 'string'
}
