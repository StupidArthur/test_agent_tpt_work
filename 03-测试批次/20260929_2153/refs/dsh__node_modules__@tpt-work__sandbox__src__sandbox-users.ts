/**
 * 沙箱用户凭据读写（research/codex-elevated-sandbox-blueprint 提权路径）。
 *
 * codex 官方 `sandbox-setup.exe` 在 `<codex_home>/` 下产出两份产物（布局对齐
 * `windows-sandbox-rs/src/setup.rs` 的 `sandbox_dir`/`sandbox_secrets_dir`/`setup_marker_path`）：
 *  - `<codex_home>/.sandbox/setup_marker.json`：`{version, offline_username, online_username, …}`。
 *  - `<codex_home>/.sandbox-secrets/sandbox_users.json`：`{version, offline:{username,password},
 *    online:{…}}`，`password` = base64(DPAPI protect)，绑定产出它时的用户上下文。
 *
 * ⚠ v5 起 codex 把 `sandbox_users.json` 从 `.sandbox/` **移到 `.sandbox-secrets/`**（setup 会删旧
 * 位置的 legacy 文件），且 `.sandbox-secrets` 对沙箱组 DENY ⇒ 只有真实用户读得到凭据。
 *
 * 本模块只**读**这两份产物（非提权父进程 `dpapiUnprotect` 拿回明文密码），不自行建用户——
 * 建用户/写 marker 由 codex 官方 setup 二进制完成（避免复刻其 SETUP_VERSION/ACL 语义）。
 * @module
 */

import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { dpapiUnprotect } from './win32.ts'

/** marker 所在子目录（codex `sandbox_dir`）。 */
export const SANDBOX_SUBDIR = '.sandbox'
/** 凭据所在子目录（codex `sandbox_secrets_dir`；v5 起从 `.sandbox/` 迁来）。 */
export const SANDBOX_SECRETS_SUBDIR = '.sandbox-secrets'
export const SANDBOX_USERS_FILE = 'sandbox_users.json'
export const SETUP_MARKER_FILE = 'setup_marker.json'

/**
 * 我方沙箱本地账号名（implementation/sandbox-decodex-rename-acl-elevated-modes W6 去 codex 字眼）。定义在本模块而不是 `setup.ts`：这两份产物
 * 的**就绪判定**要看它，而 `setup.ts` 反过来 import 本模块 —— 常量放对面会成 import 环。
 * （`setup.ts` 仍 re-export 它们，公共导出不变。）
 *
 * 这两个名字是**我方通过 payload 指定**的（`offline_username`/`online_username`），改名可行；而
 * **组名 `CodexSandboxUsers` 改不了** —— 它硬编码在已签名的 setup 二进制里（payload 里没有组名
 * 字段，传不进去），只能留原样。账号与组是两件事，别把这条当成那条。
 *
 * 改名同时**消掉一个真实的凭据互踩**：上游 codex CLI 用它自己的 `CodexSandboxOffline/Online`
 * 跑同一份 setup，而 setup 每次都会重置账号口令 ⇒ 共用账号名时谁后跑 setup 谁的口令有效，另一方
 * 存的 DPAPI 口令就地失效，现场是 `CreateProcessWithLogonW failed err=1326`
 * （`ERROR_LOGON_FAILURE`，research/codex-sandbox-vs-real-codex-cli-independence 的推断，本机见过）。账号名分开后两互不干涉，只剩共享组
 * `CodexSandboxUsers`（组成员关系可并存，里面不含口令）。
 *
 * ⚠ 改过名的机器上会留下 `CodexSandboxOffline`/`CodexSandboxOnline` 两个**孤儿账号**（我方不再
 * 使用，也登不进去）。删除需要管理员且属于机器账户，按 R8 留给人工处置，本包不删。
 */
export const OFFLINE_USERNAME = 'TptSandboxOffline'
export const ONLINE_USERNAME = 'TptSandboxOnline'

/** 一个沙箱用户的凭据（密码已解密）。 */
export interface SandboxCredential {
  username: string
  password: string
}

/** 一对沙箱用户凭据（offline = 无网络策略，online = 允许网络）。 */
export interface SandboxUsers {
  offline: SandboxCredential
  online: SandboxCredential
}

interface SandboxUserRecord {
  username?: unknown
  password?: unknown
}
interface SandboxUsersFile {
  version?: unknown
  offline?: SandboxUserRecord
  online?: SandboxUserRecord
}
interface SetupMarkerFile {
  version?: unknown
  offline_username?: unknown
  online_username?: unknown
}

export function sandboxDir(sandboxHome: string): string {
  return join(sandboxHome, SANDBOX_SUBDIR)
}
/** 凭据目录（codex `sandbox_secrets_dir`；setup 对它给沙箱组 DENY）。 */
export function sandboxSecretsDir(sandboxHome: string): string {
  return join(sandboxHome, SANDBOX_SECRETS_SUBDIR)
}
export function sandboxUsersPath(sandboxHome: string): string {
  return join(sandboxSecretsDir(sandboxHome), SANDBOX_USERS_FILE)
}
export function setupMarkerPath(sandboxHome: string): string {
  return join(sandboxDir(sandboxHome), SETUP_MARKER_FILE)
}

/** 两份产物是否都存在（不校验版本语义）。 */
export function sandboxSetupPresent(sandboxHome: string): boolean {
  return existsSync(sandboxUsersPath(sandboxHome)) && existsSync(setupMarkerPath(sandboxHome))
}

function readJson<T>(path: string): T {
  return JSON.parse(readFileSync(path, 'utf8')) as T
}

function decodeCredential(record: SandboxUserRecord | undefined, what: string): SandboxCredential {
  const username = record?.username
  const password = record?.password
  if (typeof username !== 'string' || username.length === 0) {
    throw new Error(`sandbox_users.json: ${what}.username 缺失或非字符串`)
  }
  if (typeof password !== 'string' || password.length === 0) {
    throw new Error(`sandbox_users.json: ${what}.password 缺失或非字符串`)
  }
  return { username, password: dpapiUnprotect(Buffer.from(password, 'base64')) }
}

/**
 * 读取并解密一对沙箱用户凭据。
 * @param sandboxHome - codex 宿主根（`.sandbox/` 的父目录）。
 * @throws 产物缺失、字段缺失、或 DPAPI 解密失败（换用户上下文产出 ⇒ 解不开）。
 */
export function readSandboxUsers(sandboxHome: string): SandboxUsers {
  const file = readJson<SandboxUsersFile>(sandboxUsersPath(sandboxHome))
  return {
    offline: decodeCredential(file.offline, 'offline'),
    online: decodeCredential(file.online, 'online'),
  }
}

/**
 * setup 就绪判定：两份产物存在、版本一致、**里面的账号名就是我方现在用的这两个**、且凭据可被当前
 * 用户 DPAPI 解开。四者缺一即视为未就绪（fail-closed：拿不到可用凭据就不能走提权路径）。
 *
 * ⚠ 账号名核对不是洁癖，是 W6 改名带出来的**必需项**：改名后旧机器的产物在前三条上全部通过
 * （version 仍是 5、两份 json 都在、DPAPI 照样解得开），但里面记的是 `CodexSandboxOffline`，
 * 而我方 runner 拿 `TptSandboxOffline` 去登录 ⇒ `CreateProcessWithLogonW failed err=1326`
 * ——和 research/codex-sandbox-vs-real-codex-cli-independence 那种账号互踩同一个错误码，现场最难归因。判成「未就绪」才会走 runner 的
 * fail-closed 提示（让人去跑一次性 setup），而不是带着对不上的凭据硬跑。
 */
export function sandboxSetupComplete(sandboxHome: string): boolean {
  if (!sandboxSetupPresent(sandboxHome)) return false
  try {
    const users = readJson<SandboxUsersFile>(sandboxUsersPath(sandboxHome))
    const marker = readJson<SetupMarkerFile>(setupMarkerPath(sandboxHome))
    if (users.version !== marker.version) return false
    if (typeof users.version !== 'number') return false
    if (marker.offline_username !== OFFLINE_USERNAME || marker.online_username !== ONLINE_USERNAME) return false
    if (users.offline?.username !== OFFLINE_USERNAME || users.online?.username !== ONLINE_USERNAME) return false
    readSandboxUsers(sandboxHome)
    return true
  } catch {
    return false
  }
}
