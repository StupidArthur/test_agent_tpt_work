/**
 * sandbox-runner.exe 定位：环境变量 → TPT 数据根的安装位。
 * 不在此包内做下载（见 scripts/bootstrap.mjs，postinstall 拉取到安装位）。
 *
 * ⚠ 候选加固（2026-09-13 评审 medium）：删除 `process.cwd()/temp` 与 `%TEMP%` 两个开发探针候选
 * ——同用户可写位置的同名文件会被拉起并物化给沙箱用户（本地提权路径）。所有命中（含 env）
 * 统一过 `binaries.ts` 的 `isValidBinary`（MZ + 最小体量）再使用；env 指向无效二进制时直接
 * undefined（fail-closed，不静默回退安装位）。
 *
 * ⚠ 与 binaries.ts 双向 import：本模块只在函数体内用其判定函数（函数声明实例化期可用，
 * 无 TDZ）；两侧顶层均为纯字面量/函数声明，任意求值顺序安全。
 * @module
 */

import { homedir } from 'node:os'
import { join } from 'node:path'
import { TPT_HOME_DIR_NAME } from '@tpt-work/data-root'
import { isValidBinary, pickValidBinary, RUNNER_EXE_MIN_SIZE } from './binaries.ts'

/** sandbox-runner.exe 的安装位（相对 TPT 数据根）。 */
export function runnerInstallDir(): string {
  return join(homedir(), TPT_HOME_DIR_NAME, 'sandbox')
}

/** 依次解析 runner 绝对路径；找不到或无效返回 undefined（confine 侧据此 fail-closed）。 */
export function resolveRunnerExe(): string | undefined {
  const fromEnv = process.env.TPT_SANDBOX_RUNNER
  if (fromEnv !== undefined && fromEnv !== '') {
    return isValidBinary(fromEnv, RUNNER_EXE_MIN_SIZE) ? fromEnv : undefined
  }
  return pickValidBinary([join(runnerInstallDir(), 'sandbox-runner.exe')], RUNNER_EXE_MIN_SIZE)
}

/** runner 是否已就绪（confine/probe 门禁）。 */
export function runnerReady(): boolean {
  return resolveRunnerExe() !== undefined
}

/**
 * 默认沙箱宿主根（setup 产物 `.sandbox/` 与 runner 读取点必须落在这里，两边一致才对得上）。
 * 由 `TPT_SANDBOX_HOME` 覆盖。
 *
 * ⚠ 默认值经 `runnerInstallDir()` ⇒ 派生自 **homedir**（`~/.tpt-work/sandbox/home`），
 * **不受** `--home` / `TPT_HOME` 这类"隔离数据根"的旗标影响。任何会写档位文件
 * （`mode.json`）或跑 setup 的测试/探针都必须显式设 `TPT_SANDBOX_HOME` 指向本次新建的
 * 隔离目录，否则就直接往真实用户数据根写（本仓在 e2e 装机分支上踩过一次：跑完把
 * 用户自己的档位改成了 elevated）。
 */
export function defaultSandboxHome(): string {
  return process.env.TPT_SANDBOX_HOME ?? join(runnerInstallDir(), 'home')
}

