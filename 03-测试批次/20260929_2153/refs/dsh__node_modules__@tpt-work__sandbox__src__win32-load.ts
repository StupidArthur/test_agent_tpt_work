/**
 * Win32 koffi 库的**惰性装载**工具（本包唯一装载 Windows DLL 的入口）。
 *
 * 为什么是硬要求而不是优化：`@deepseek-ai/dsh-sandbox-local` **静态** import 本包
 * （见 `patches/@deepseek-ai__dsh-sandbox-local.patch`），而 sandbox-local 是 `dsh-base`
 * 装配里 id=`sandbox` 的常驻 entry ⇒ cordis loader 在**任何平台**启动期都会加载本包模块图。
 * 顶层 `koffi.load('kernel32.dll')` 在非 Windows 上必然 `Failed to load shared library`，
 * 后果不是「沙箱不可用」而是**整个 plugin tree apply 失败、backend 起不来**
 * （Linux 上 sandbox-local 本该走 bwrap/landlock 链，与本包的 ACL/提权路径无关）。
 * 对照：上游 `@deepseek-ai/dsh-sandbox-windows-acl` 在 Linux 上可 import，正因为它不在导入期解析 DLL。
 *
 * 语义等价口径：只是把 dlopen 延后到**首次真正使用**，DLL 名、函数签名、调用顺序一字不动；
 * Windows 上的行为与改动前完全一致（首用即装载并 memo）。非 Windows 上首用抛明确错误
 * （比 koffi 的 `Failed to load shared library` 更可读），与 Windows 上「DLL 缺失」同形 fail-closed。
 * @module
 */

import koffi, { type LibraryHandle } from 'koffi'

/**
 * 装载一个 Windows 系统 DLL；非 Windows 平台直接抛（不去 dlopen）。
 * @param name - DLL 文件名（`kernel32.dll` 等）。
 */
export function loadWin32Library(name: string): LibraryHandle {
  if (process.platform !== 'win32') {
    throw new Error(
      `@tpt-work/sandbox: ${name} 仅 Windows 可用（当前平台 ${process.platform}）；受限命令 fail-closed，勿在非 Windows 上调用 Win32 路径`,
    )
  }
  return koffi.load(name)
}

/**
 * memo 化的惰性求值（成功才缓存；失败每次重试，错误原样抛出）。
 * 用于把 `lib.func(...)` 绑定从模块顶层推到首次调用点。
 */
export function lazily<T>(factory: () => T): () => T {
  let cache: T | undefined
  return () => {
    if (cache === undefined) cache = factory()
    return cache as T
  }
}
