/**
 * 上游 dsh ACL 沙箱库（`@deepseek-ai/dsh-sandbox-windows-acl`）的**唯一**取用点。
 *
 * 为什么不是 `import` 语句而是惰性 `require(esm)`（三条各自成立的理由）：
 *
 *  1. **本包的 `index` 被 `dsh-sandbox-local` 静态 import**，而 sandbox-local 是各平台常驻 entry
 *     （见 `win32-load.ts` 的同款告诫）。上游那一串模块在 import 期就拉起 `koffi` 与
 *     `@deepseek-ai/dsh-win32-process` ⇒ 顶层静态 import 等于让 Linux/macOS 宿主为一个 Windows-only
 *     后端加载原生绑定。
 *  2. seam 侧的调用点全是**同步**的（`AclWriteGrant.create()` / `workspaceWriteSid()` 都在
 *     `windowsAclRunnerArgv()` 的同步路径上）⇒ 动态 `import()` 的 Promise 在这里用不了。
 *     Node ≥22.12 的 `require(esm)` 对无顶层 await 的 ESM 图可同步取命名空间（本机实测 11 ms，
 *     导出内容 `AclSandbox/AclWriteGrant/assertTempRootOutsideWorkspace/tempWriteSid/workspaceWriteSid`，
 *     且 `workspaceWriteSid('C:\\Projects\\tpt-work')` 与我方原副本逐字节同形）。
 *  3. ACL 档以外（Linux/macOS、以及提权档的宿主装配）根本不该为它付加载成本。
 *
 * ⚠ 上游是**默认档的实现本体**：ACL 档下 SID 派生、授权语义、runner 全部由它负责，我方不再留
 * 一份同形副本（副本会漂）。要换实现版本 = 改 pin，不是改这里。
 * @module @tpt-work/sandbox/upstream-acl
 */

import { createRequire } from 'node:module'

/** 上游包名（ACL 档的实现本体）。只用于错误文案；**加载点用的是字面量**，见下。 */
export const UPSTREAM_ACL_PACKAGE = '@deepseek-ai/dsh-sandbox-windows-acl'

/** 上游写授权实例（只声明本包真正会用到的成员，避免把上游内部类型当契约）。 */
export interface UpstreamWriteGrant {
  /** SDDL 形式的写能力 SID。 */
  readonly writeSid: string
  /** 给一个目录授写；`standing` = 常驻 ACE（dispose 不撤销）。 */
  add(path: string, standing?: boolean): void
  /** 当前带该授权的目录，按授权顺序。 */
  readonly paths: readonly string[]
  /** 撤销可回收授权并释放 SID；所有清理失败都会报出来。 */
  dispose(): void
}

/** 本包用到的上游导出内容。 */
export interface UpstreamAclModule {
  AclWriteGrant: {
    create(writeSid: string): UpstreamWriteGrant
  }
  assertTempRootOutsideWorkspace(workspaceRoot: string, tempRoot: string): void
  tempWriteSid(tempDir: string): string
  workspaceWriteSid(workspaceRoot: string): string
}

const requireModule = createRequire(import.meta.url)

let cached: UpstreamAclModule | undefined

/**
 * 取上游模块（首次调用时加载并缓存）。
 *
 * ⚠ 这里**必须**用字符串字面量调 `require`，不能改成用上面那个常量：打包链
 * `bakeShippedExternal` 靠扫产物里的裸串决定「哪些包要有真文件随包」，变量拼出来的 specifier
 * 扫不到 ⇒ 包不会随包 ⇒ 装机上 ACL 档（也就是默认档）第一次受限执行就 `Cannot find package`。
 * 同一个包还另有一条兜底：它已登记进 `packages/host/external.json`（implementation/sandbox-decodex-rename-acl-elevated-modes W1 起该清单是一等
 * 随包来源）。两条都要在，别再退回「只靠一条」。
 * @returns 上游命名空间中本包用到的那一小片。
 * @throws 上游包不在树上时抛出带指明的错误（fail-closed：绝不静默退回到另一档的实现）。
 */
export function upstreamAcl(): UpstreamAclModule {
  if (cached !== undefined) return cached
  try {
    cached = requireModule('@deepseek-ai/dsh-sandbox-windows-acl') as UpstreamAclModule
  } catch (error) {
    throw new Error(
      `受限执行需要 ${UPSTREAM_ACL_PACKAGE}（ACL 档的实现本体），但它无法解析：`
      + `${error instanceof Error ? error.message : String(error)}`,
      { cause: error },
    )
  }
  return cached
}
