function readJson(path) {
	return JSON.parse(readFileSync(path, "utf8"));
}
function decodeCredential(record, what) {
	const username = record?.username;
	const password = record?.password;
	if (typeof username !== "string" || username.length === 0) throw new Error(`sandbox_users.json: ${what}.username 缺失或非字符串`);
	if (typeof password !== "string" || password.length === 0) throw new Error(`sandbox_users.json: ${what}.password 缺失或非字符串`);
	return {
		username,
		password: dpapiUnprotect(Buffer.from(password, "base64"))
	};
}
/**
* 读取并解密一对沙箱用户凭据。
* @param sandboxHome - codex 宿主根（`.sandbox/` 的父目录）。
* @throws 产物缺失、字段缺失、或 DPAPI 解密失败（换用户上下文产出 ⇒ 解不开）。
*/
function readSandboxUsers(sandboxHome) {
	const file = readJson(sandboxUsersPath(sandboxHome));
	return {
		offline: decodeCredential(file.offline, "offline"),
		online: decodeCredential(file.online, "online")
	};
}
/**
* setup 就绪判定：两份产物存在、版本一致、**里面的账号名就是我方现在用的这两个**、且凭据可被当前
* 用户 DPAPI 解开。四者缺一即视为未就绪（fail-closed：拿不到可用凭据就不能走提权路径）。
*
* ⚠ 账号名核对不是洁癖，是 W6 改名带出来的**必需项**：改名后旧机器的产物在前三条上全部通过
* （version 仍是 5、两份 json 都在、DPAPI 照样解得开），但里面记的是 `CodexSandboxOffline`，
* 而我方 runner 拿 `TptSandboxOffline` 去登录 ⇒ `CreateProcessWithLogonW failed err=1326`
* ——和 research/codex-sandbox-vs-real-codex-cli-independence 那种账号互踩同一个错误码，现场最难归因。判成「未就绪」才会走 runner 的
* fail-closed 提示（让人去跑一次性 setup），而不是带着对不上的凭据硬跑。
*/
function sandboxSetupComplete(sandboxHome) {
	if (!sandboxSetupPresent(sandboxHome)) return false;
	try {
		const users = readJson(sandboxUsersPath(sandboxHome));
		const marker = readJson(setupMarkerPath(sandboxHome));
		if (users.version !== marker.version) return false;
		if (typeof users.version !== "number") return false;
		if (marker.offline_username !== "TptSandboxOffline" || marker.online_username !== "TptSandboxOnline") return false;
		if (users.offline?.username !== "TptSandboxOffline" || users.online?.username !== "TptSandboxOnline") return false;
		readSandboxUsers(sandboxHome);
		return true;
	} catch {
		return false;
	}
}
