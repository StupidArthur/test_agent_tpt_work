import assert from 'node:assert/strict';
import fs from 'node:fs';
import {discover,discovery,orderedFunctions} from '../automation/discovery.mjs';
const functions=JSON.parse(fs.readFileSync(new URL('../business/catalog.json',import.meta.url),'utf8')).functions;
for(const name of Object.keys(discovery.contracts))assert(functions.some(f=>f.name===name),'Unknown annotated function '+name);
const direct=discover(functions,'技能 新建会话',{module:'skills',limit:3});assert.equal(direct.candidates[0].name,'skills.useSkillDirect');assert(direct.candidates[0].limits.includes('sessionBefore'));
assert.equal(discover(functions,'当前任务权限',{limit:3}).candidates[0].name,'conversation.setTaskPermission');
assert.equal(discover(functions,'末尾可见',{module:'experts'}).candidates[0].name,'experts.scrollPromptToEnd');
assert.equal(discover(functions,'SKILLS.USESKILLDIRECT').candidates[0].name,'skills.useSkillDirect');
assert(discover(functions,'技能',{limit:2}).candidates.length<=2);
assert.equal(discover(functions,'不存在的随机词abcdef').candidates.length,0);
assert.throws(()=>discover(functions,'技能',{limit:0}));
assert.deepEqual(orderedFunctions([...functions].reverse()).map(f=>f.name),orderedFunctions(functions).map(f=>f.name));
